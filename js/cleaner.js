/* ===================================================================
   «Учу по ФРП» — очистка текста материалов от информационного шума.
   Удаляет: номера страниц, колонтитулы, водяные знаки и служебные надписи,
   лишние пустые строки и пробелы, подряд идущие дубли строк, переносы слов.
   Не трогает содержательный текст, абзацы и авторскую пунктуацию.
   Возвращает очищенный текст и список удалённого, чтобы пользователь видел,
   что убрано, и мог откатить.
   Работает в браузере (window.Cleaner) и в Node (module.exports).
   =================================================================== */
(function (root) {
  "use strict";

  /* Служебные надписи и водяные знаки: строка удаляется целиком, только если она короткая и состоит из такой надписи */
  const WATERMARKS = [
    /^(скачано|загружено|материал (взят|скачан)|документ (скачан|загружен))(?:(?<=[A-Za-z0-9_А-Яа-яЁё])(?![A-Za-z0-9_А-Яа-яЁё])|(?<![A-Za-z0-9_А-Яа-яЁё])(?=[A-Za-z0-9_А-Яа-яЁё])).{0,80}$/i,
    /^(источник\s*:\s*)?(www\.)?(infourok|multiurok|nsportal|pedsovet|uchportal|kopilkaurokov|videouroki|znanio|urok\.1sept|prodlenka|solncesvet)\.\S*\s*$/i,
    /^(инфоурок|мультиурок|копилка уроков|видеоуроки)(\s*[—–-].{0,40})?$/i,
    /^(page|страница|стр\.?)\s*\d{1,4}(\s*(of|из)\s*\d{1,4})?\s*$/i,
    /^[-–—]\s*\d{1,4}\s*[-–—]$/,
    /^(evaluation only|created with|created by|demo version|trial version|unregistered|пробная версия|демо-?версия|демонстрационная версия)(?:(?<=[A-Za-z0-9_А-Яа-яЁё])(?![A-Za-z0-9_А-Яа-яЁё])|(?<![A-Za-z0-9_А-Яа-яЁё])(?=[A-Za-z0-9_А-Яа-яЁё])).{0,80}$/i,
    /^(converted by|generated by|printed by|powered by)(?:(?<=[A-Za-z0-9_А-Яа-яЁё])(?![A-Za-z0-9_А-Яа-яЁё])|(?<![A-Za-z0-9_А-Яа-яЁё])(?=[A-Za-z0-9_А-Яа-яЁё])).{0,80}$/i,
    /^this (document|file) (was|is) (created|generated)(?:(?<=[A-Za-z0-9_А-Яа-яЁё])(?![A-Za-z0-9_А-Яа-яЁё])|(?<![A-Za-z0-9_А-Яа-яЁё])(?=[A-Za-z0-9_А-Яа-яЁё])).{0,80}$/i,
    /^(все права защищены|all rights reserved)\.?\s*$/i,
    /^\s*(©|\(c\))\s*(инфоурок|infourok|мультиурок|multiurok)(?:(?<=[A-Za-z0-9_А-Яа-яЁё])(?![A-Za-z0-9_А-Яа-яЁё])|(?<![A-Za-z0-9_А-Яа-яЁё])(?=[A-Za-z0-9_А-Яа-яЁё])).{0,60}$/i
  ];
  /* Строки-структура урока: не колонтитулы, даже если повторяются */
  const KEEP = /^(ход урока|слово учителя|учитель|ученик|ученики|беседа|ответ|вопросы?( и задания)?|задани[ея]|упражнени[ея]|образец( ответа)?|домашнее задание|рефлексия|вывод|итог|цель|оборудование|тип урока|план|этап|уроки? №?|тема|глава|часть|раздел|§|карточка|[ivxlc]+\.|#\.|#\)|[а-е]\))/i;

  const norm = l => l.toLowerCase().replace(/ё/g, "е").replace(/\d+/g, "#").replace(/[ \t]+/g, " ").trim();
  const isPageNum = l => /^\s*[-–—]?\s*\d{1,4}\s*[-–—]?\s*$/.test(l);

  /* Номера страниц: чистые числа, которые идут по возрастанию через весь документ.
     Ищем самую длинную возрастающую цепочку с шагом 1–3: это и есть нумерация страниц,
     одиночные числа вне цепочки (номера в таблицах) остаются. */
  function pageNumberLines(lines) {
    const cand = [];
    lines.forEach((l, i) => { if (isPageNum(l)) cand.push({ i, n: parseInt(l.replace(/\D/g, ""), 10) }); });
    if (cand.length < 3) return new Set();
    const best = new Array(cand.length).fill(1), prev = new Array(cand.length).fill(-1);
    for (let a = 0; a < cand.length; a++) {
      for (let b = Math.max(0, a - 40); b < a; b++) {
        const d = cand[a].n - cand[b].n;
        if (d >= 1 && d <= 3 && best[b] + 1 > best[a]) { best[a] = best[b] + 1; prev[a] = b; }
      }
    }
    let end = best.indexOf(Math.max(...best));
    if (best[end] < 3) return new Set();
    const out = new Set();
    while (end >= 0) { out.add(cand[end].i); end = prev[end]; }
    return out;
  }

  /* Колонтитулы: короткая строка повторяется 3+ раза и почти всегда стоит у границы страницы
     (рядом с номером страницы или с символом разрыва страницы). */
  function headerLines(lines, pageIdx, pageBreaks) {
    const near = i => {
      for (let d = -3; d <= 3; d++) { const j = i + d; if (j !== i && (pageIdx.has(j) || pageBreaks.has(j))) return true; }
      return false;
    };
    const groups = new Map();
    lines.forEach((l, i) => {
      if (!l.trim() || pageIdx.has(i)) return;
      const k = norm(l); if (k.length < 3 || k.length > 90) return;
      if (!groups.has(k)) groups.set(k, []);
      groups.get(k).push(i);
    });
    const out = new Set();
    for (const [k, idx] of groups) {
      if (idx.length < 3) continue;
      if (KEEP.test(k)) continue;
      const nearShare = idx.filter(near).length / idx.length;
      const spread = idx[idx.length - 1] - idx[0] > lines.length * 0.2;
      if (nearShare >= 0.6 && spread) idx.forEach(i => out.add(i));
    }
    return out;
  }

  /* Документ вставлен в файл несколько раз подряд (частая ошибка при копировании): оставляем одну копию —
     ту, где лучше сохранены абзацы. Копии ищем по повтору первой содержательной строки. */
  function dropRepeatedCopies(text, note) {
    const lines = text.split("\n");
    const first = lines.find(l => l.trim().length >= 40);
    if (!first) return text;
    const key = first.trim();
    const starts = []; lines.forEach((l, i) => { if (l.trim() === key) starts.push(i); });
    if (starts.length < 2) return text;
    const segs = starts.map((s, k) => lines.slice(s, k + 1 < starts.length ? starts[k + 1] : lines.length).join("\n"));
    const flat = s => s.replace(/\s+/g, "");
    const a = flat(segs[0]);
    const same = segs.every(s => { const b = flat(s); return Math.abs(b.length - a.length) / Math.max(a.length, 1) < 0.03 && [0.1, 0.3, 0.5, 0.7, 0.9].every(p => b.includes(a.slice(Math.floor(a.length * p), Math.floor(a.length * p) + 40))); });
    if (!same) return text;
    const best = segs.reduce((x, y) => ((y.match(/\n/g) || []).length > (x.match(/\n/g) || []).length ? y : x));
    note("Повторы всего документа", `${segs.length} копии, оставлена одна`);
    return lines.slice(0, starts[0]).join("\n") + (starts[0] ? "\n" : "") + best;
  }

  function clean(input, opts = {}) {
    const original = String(input || "");
    const removed = new Map(); // тип → {count, samples[]}
    const note = (type, sample) => { const r = removed.get(type) || { count: 0, samples: [] }; r.count++; if (r.samples.length < 6 && sample && !r.samples.includes(sample)) r.samples.push(sample.slice(0, 120)); removed.set(type, r); };

    let t = original.replace(/\r\n?/g, "\n").replace(/­/g, "").replace(/[   ]/g, " ").replace(/\t/g, " ");
    // символ разрыва страницы (\f) — знак границы страницы
    let lines = t.split("\n");
    const pageBreaks = new Set();
    lines = lines.map((l, i) => { if (l.includes("\f")) { pageBreaks.add(i); return l.replace(/\f/g, ""); } return l; });
    // в тексте из PDF страницы склеены пустой строкой: если пустых строк мало, считаем их границами страниц
    const blanks = lines.filter(l => !l.trim()).length;
    if (opts.pdf && blanks < lines.length / 6) lines.forEach((l, i) => { if (!l.trim()) pageBreaks.add(i); });

    // 1. номера страниц
    const pageIdx = pageNumberLines(lines);
    // 2. колонтитулы
    const headIdx = headerLines(lines, pageIdx, pageBreaks);
    // 3. водяные знаки и служебные надписи
    const out = [];
    lines.forEach((l, i) => {
      const s = l.trim();
      if (pageIdx.has(i)) { note("Номера страниц", s); return; }
      if (headIdx.has(i)) { note("Колонтитулы", s); return; }
      if (s && s.length < 140 && WATERMARKS.some(re => re.test(s))) { note("Водяные знаки и служебные надписи", s); return; }
      out.push(l);
    });

    // 4. переносы слов: «сло-\nво» → «слово» (обе части — строчные буквы); мягкий перенос «¬»
    let text = dropRepeatedCopies(out.join("\n"), note);
    // разрядка: «Уч и т е л ь» → «Учитель» (5+ кусочков по 1–2 буквы подряд, в основном одиночные буквы)
    text = text.replace(/(^|[\s(«"—–])((?:[А-ЯЁа-яё]{1,2} )(?:[А-ЯЁа-яё] ){3,}[А-ЯЁа-яё])(?=[\s.,:;!?»")]|$)/gm, (m, pre, w) => {
      const parts = w.split(" "); if (/^[йьъыЙЬЪЫ]$/.test(parts[0])) return m;
      note("Разрядка (буквы через пробел)", w); return pre + parts.join("");
    });
    text = text.replace(/([а-яёa-z])[-‐¬]\s*\n\s*([а-яёa-z])/g, (m, a, b) => { note("Разорванные слова (переносы)", m.replace(/\s+/g, " ")); return a + b; });

    // 5. лишние пробелы внутри строк и в концах строк
    let spaces = 0;
    text = text.split("\n").map(l => { const n = l.replace(/ {2,}/g, " ").replace(/\s+$/, ""); if (n !== l) spaces++; return n; }).join("\n");
    if (spaces) removed.set("Лишние пробелы", { count: spaces, samples: [] });

    // 6. дубли: одна и та же строка подряд
    const ded = [];
    text.split("\n").forEach(l => {
      const prev = ded.length ? ded[ded.length - 1] : null;
      if (l.trim().length > 3 && prev !== null && prev.trim() === l.trim()) { note("Дублирующиеся строки", l.trim()); return; }
      ded.push(l);
    });
    text = ded.join("\n");

    // 7. строки, разорванные посередине предложения (PDF): склеиваем, если строка не кончается знаком конца
    //    и следующая начинается со строчной буквы. Короткие строки (стихи, заголовки) и нумерованные пункты не трогаем.
    if (opts.reflow !== false) {
      let joins = 0;
      const L = text.split("\n"), R = [];
      for (let i = 0; i < L.length; i++) {
        const cur = L[i];
        if (R.length) {
          const prev = R[R.length - 1];
          if (prev.length >= 50 && /[^.!?:;»"…)\]\s]$/.test(prev) && /^[а-яёa-z(«"]/.test(cur)) { R[R.length - 1] = prev + " " + cur; joins++; continue; }
        }
        R.push(cur);
      }
      text = R.join("\n");
      if (joins) removed.set("Разрывы строк внутри предложений", { count: joins, samples: [] });
    }

    // 8. пустые строки: не больше одной подряд; пустые строки в начале и конце
    const before = text;
    text = text.replace(/\n[ \t]*\n(?:[ \t]*\n)+/g, "\n\n").replace(/^\s+|\s+$/g, "");
    const emptyRemoved = (before.match(/\n/g) || []).length - (text.match(/\n/g) || []).length;
    if (emptyRemoved > 0) removed.set("Пустые строки", { count: emptyRemoved, samples: [] });

    const report = [...removed.entries()].map(([type, r]) => ({ type, count: r.count, samples: r.samples }));
    return { text, report, stats: { before: original.length, after: text.length, removedChars: Math.max(0, original.length - text.length) } };
  }

  /* Краткий отчёт строкой: «номера страниц — 129, колонтитулы — 26…» */
  function summary(report) {
    return (report || []).filter(r => r.count).map(r => `${r.type.toLowerCase()} — ${r.count}`).join("; ") || "шума не найдено";
  }

  const Cleaner = { clean, summary, pageNumberLines, isPageNum };
  if (typeof module !== "undefined" && module.exports) module.exports = Cleaner;
  else root.Cleaner = Cleaner;
})(typeof window !== "undefined" ? window : globalThis);
