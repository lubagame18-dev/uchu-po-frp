/* «Учу по ФРП» — заполнение тем, у которых не было содержания.
   Аудит нашёл 31 тему с пустым содержанием (краеведение и обобщения по истории,
   «Резервное время» по географии, повторительно-обобщающие уроки по
   обществознанию). Здесь содержание и виды деятельности дописываются по
   понятным правилам: никаких выдуманных фактов, только рамка работы.

   Модуль идемпотентен: заполняет только пустые поля и не трогает заполненные.
   Формулировки собственные, тексты учебников не используются. */
window.FRP_EXTRAS = window.FRP_EXTRAS || [];

window.FRP_EXTRAS.push(function () {
  "use strict";
  const P = window.FRPPlans;
  if (!P) return;

  const has = (s) => String(s || "").trim().length >= 5;
  const quoted = (t) => {
    const m = String(t).match(/[«"]([^»"]+)[»"]/);
    return m ? m[1] : String(t).replace(/^повторительно-обобщающий урок по теме\s*/i, "").replace(/^повторение и обобщение по (теме|разделу)\s*/i, "").trim();
  };
  const fill = (theme, content, acts) => {
    if (!has(theme[1]) && content) theme[1] = content;
    if (!has(theme[2]) && acts) theme[2] = acts;
  };

  /* география: резервные уроки в каждом классе */
  const geo = P.geo || {};
  Object.keys(geo).forEach(g => {
    (geo[g].th || []).forEach(t => {
      if (/^резервное время$/i.test(String(t[0]).trim())) {
        fill(t,
          `Повторение и обобщение курса географии ${g} класса: ключевые понятия, карты и практические умения; подготовка к итоговой работе.`,
          "Повторять ключевые понятия; работать с картами; выполнять итоговые задания.");
      }
    });
  });

  /* история: введение, краеведение и обобщения */
  const hist = P.hist || {};
  Object.keys(hist).forEach(g => {
    (hist[g].th || []).forEach(t => {
      const title = String(t[0]).trim();
      if (/^введение$/i.test(title)) {
        fill(t,
          "Знакомство с курсом: цели и структура, основные источники и хронологические рамки.",
          "Обсуждать цели курса; работать с учебником, картой и лентой времени.");
      } else if (/^наш край/i.test(title)) {
        const period = title.replace(/^наш край/i, "").replace(/^в\s*/i, "").replace(/\.$/, "").trim();
        fill(t,
          `История родного края${period ? " в " + period : ""}: основные события, памятники и люди; связь с историей страны.`,
          "Работать с краеведческим материалом; готовить сообщение о родном крае.");
      } else if (/^(повторение и обобщение|обобщение по теме)/i.test(title)) {
        const topic = quoted(title);
        fill(t,
          `Систематизация знаний по теме${topic ? " «" + topic + "»" : ""}: ключевые события, понятия и причинно-следственные связи; подготовка к итоговой работе.`,
          "Обобщать материал; заполнять таблицы и схемы; решать итоговые задания.");
      }
    });
  });

  /* обществознание: повторительно-обобщающие уроки (виды деятельности уже есть) */
  const soc = P.soc || {};
  Object.keys(soc).forEach(g => {
    (soc[g].th || []).forEach(t => {
      const title = String(t[0]).trim();
      if (/^повторительно-обобщающий урок/i.test(title)) {
        const topic = quoted(title);
        fill(t,
          `Обобщение по теме${topic ? " «" + topic + "»" : ""}: ключевые понятия, связи и примеры из жизни общества; подготовка к проверочной работе.`,
          "Систематизировать материал; приводить примеры; выполнять проверочные задания.");
      }
    });
  });
});
