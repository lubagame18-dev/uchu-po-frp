/* «Учу по ФРП» — технология 1–4 классов без нейросети.
   Уроки-практикумы: материалы и инструменты, инструкционная карта, операции,
   техника безопасности, выставка и оценка изделия. */
window.TechPrimary = (() => {
  "use strict";
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const KINDS = {
    paper: { name: "бумага и картон", props: ["легко режется", "сгибается", "клеится", "впитывает воду"], tools: ["ножницы", "клей", "линейка", "карандаш"], steps: ["Разметить детали по шаблону.", "Вырезать по линии.", "Согнуть по намеченной линии.", "Склеить детали.", "Проверить прочность и аккуратность."] },
    fabric: { name: "ткань", props: ["мягкая", "сыпучая по краю", "шьётся иглой", "можно клеить флизелином"], tools: ["игла", "нитки", "ножницы", "булавки"], steps: ["Разметить детали на ткани.", "Вырезать с припуском.", "Сметать детали.", "Сшить швом «вперёд иголку».", "Проверить ровность шва."] },
    plastic: { name: "пластилин и природные материалы", props: ["пластилин мягкий, держит форму", "природные материалы разные по форме"], tools: ["стека", "дощечка", "клей", "ножницы"], steps: ["Размять пластилин.", "Слепить основу.", "Добавить детали.", "Соединить с природным материалом.", "Выровнять поверхность."] },
    model: { name: "конструктор и модели", props: ["детали соединяются", "важна последовательность", "модель должна стоять устойчиво"], tools: ["детали конструктора", "схема", "линейка"], steps: ["Рассмотреть схему.", "Найти нужные детали.", "Собрать основу.", "Добавить узлы.", "Проверить устойчивость."] },
    project: { name: "проект", props: ["есть замысел и результат", "важно планировать", "нужна защита проекта"], tools: ["материалы по выбору", "эскиз", "инструкционная карта"], steps: ["Выбрать идею.", "Нарисовать эскиз.", "Составить инструкционную карту.", "Изготовить изделие.", "Испытать и представить."] }
  };
  function kindOf(topic) {
    const t = norm(topic);
    if (/бумаг|картон|апплик|оригам/.test(t)) return "paper";
    if (/ткан|шв|шить|игол|нитки|фартук/.test(t)) return "fabric";
    if (/пластилин|природн|шишк|лист|глина/.test(t)) return "plastic";
    if (/конструктор|модел|механизм|сборк/.test(t)) return "model";
    if (/проект|изделие|поделк/.test(t)) return "project";
    return "paper";
  }
  const Q = {
    paper: [["Зачем нужна разметка?", "чтобы детали совпали по размеру"], ["Как резать ножницами?", "по линии, от себя, поворачивая бумагу"], ["Как склеить прочно?", "нанести клей тонким слоем, прижать"], ["Как проверить качество?", "сравнить с образцом, проверить размеры"]],
    fabric: [["Почему ткань осыпается?", "края нитей свободны, нужно обрабатывать"], ["Как вдеть нитку в иглу?", "сложить конец, вдеть, завязать узелок"], ["Каким швом сшивают?", "«вперёд иголку»"], ["Как безопасно работать с иглой?", "хранить в игольнице, не брать в рот"]],
    plastic: [["Как лепить аккуратно?", "размять, работать на дощечке, выравнивать"], ["Как соединить детали?", "прижать, примазать, использовать стеку"], ["Как хранить пластилин?", "в коробке, отдельно по цветам"], ["Что важно в работе с природным материалом?", "подобрать по форме и размеру"]],
    model: [["Зачем нужна схема?", "чтобы собрать по порядку"], ["Что проверяют после сборки?", "устойчивость и прочность"], ["Как найти ошибку?", "сравнить со схемой, проверить каждый узел"], ["Что делать, если детали не хватает?", "подобрать замену по размеру"]],
    project: [["С чего начинается проект?", "с идеи и потребности"], ["Что такое инструкционная карта?", "план изготовления с материалами и инструментами"], ["Как оценить проект?", "качество, аккуратность, польза, защита"], ["Зачем защита проекта?", "объяснить замысел и результат"]]
  };
  function conspect(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), K = KINDS[kind], qa = Q[kind];
    const rows = [
      ["1", "Организационный момент", "1–2", "Проверка материалов и инструментов, рабочего места."],
      ["2", "Инструктаж по технике безопасности", "2–3", `Правила работы: ${kind === "fabric" ? "игла хранится в игольнице, ножницы передаём кольцами вперёд" : "ножницы передаём кольцами вперёд, клей не пробуем"}.`],
      ["3", "Анализ образца", "5–6", `Рассматриваем изделие. Материал: ${K.name}. Свойства: ${K.props.join(", ")}. Инструменты: ${K.tools.join(", ")}.`],
      ["4", "Планирование (инструкционная карта)", "6–8", `Составляем план: ${K.steps.slice(0, 3).join(" ")}`],
      ["5", "Физминутка", "2", "Разминка для рук и глаз."],
      ["6", "Практическая работа", "16–18", `Выполняем изделие по инструкционной карте: ${K.steps.slice(3).join(" ")} Учитель помогает, следит за безопасностью.`],
      ["7", "Выставка и оценка", "4–5", "Рассматриваем изделия, сравниваем с образцом, обсуждаем качество."],
      ["8", "Итог и рефлексия", "2–3", "Что получилось? Что было трудно? Где пригодится изделие?"],
      ["9", "Домашнее задание", "1", "Принести материалы, подготовить эскиз."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const kart = "| № | Этап | Материалы и инструменты | Правила безопасности |\n|---|---|---|---|\n" + K.steps.map((s, i) => `| ${i + 1} | ${s} | ${K.tools.join(", ")} | аккуратно, по инструкции |`).join("\n");
    const qaT = "| № | Вопрос | Ответ |\n|---|---|---|\n" + qa.map((x, i) => `| ${i + 1} | ${x[0]} | ${x[1]} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Технология · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Учить работать с материалом «${K.name}» по инструкционной карте, соблюдать безопасность и оценивать качество изделия.`,
      "",
      "## Материалы и инструменты",
      `${K.tools.join(", ")}; материалы по теме.`,
      "",
      "## Опорные знания",
      K.props.map(x => "- " + x).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Инструкционная карта",
      kart,
      "",
      "## Вопросы и ответы",
      qaT,
      "",
      "## Критерии оценивания",
      "Точность разметки, аккуратность, прочность, безопасность, самостоятельность, законченность.",
      "",
      "## Домашнее задание",
      `Подготовить эскиз и материалы по теме «${p.topic}».`
    ].join("\n");
  }
  function worksheet(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), K = KINDS[kind];
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. Материал и свойства",
      K.props.map(x => "- " + x).join("\n"),
      "",
      "## 2. Инструменты",
      K.tools.join(", "),
      "",
      "## 3. Инструкционная карта",
      "| № | Действие | Материалы | Безопасность |\n|---|---|---|---|\n" + K.steps.map((s, i) => `| ${i + 1} | ${s} | | |`).join("\n"),
      "",
      "## 4. Техника безопасности",
      "Напиши 2 правила работы с инструментами: ______________________",
      "",
      "## 5. Самооценка",
      "Аккуратность ✓/✗  Прочность ✓/✗  Безопасность ✓/✗",
      "",
      "## 6. Рефлексия",
      "Что получилось? Что улучшишь?"
    ].join("\n");
  }
  return { kindOf, conspect, worksheet, lesson: conspect, KINDS };
})();
