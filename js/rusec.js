/* Дополняем локальный русский: если RuKit не дал теорию/алгоритм — подставляем. */
(function () {
  if (!window.RuKit || window.RuKit.__ruSecPatched) return;
  const orig = window.RuKit.build;
  if (typeof orig !== "function") return;
  window.RuKit.build = function (p) {
    const K = orig.call(window.RuKit, p);
    try {
      if (window.RuSec && (!K.algo || !K.theory || !K.theory.length)) {
        const extra = window.RuSec.fill(p);
        K.theory = (K.theory && K.theory.length ? K.theory : extra.theory);
        K.algo = K.algo || extra.algo;
        K.wsTasks = (K.wsTasks && K.wsTasks.length ? K.wsTasks : extra.wsTasks);
      }
    } catch (e) { }
    return K;
  };
  window.RuKit.__ruSecPatched = true;
})();
