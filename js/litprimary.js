/* «Учу по ФРП» — литературное чтение 1–4 классов без нейросети.
   Задания в формате рабочих тетрадей и учебников: чтение, вопросы, план,
   пересказ, выразительное чтение, средства выразительности, творческая работа.
   Тексты — общественное достояние или краткие авторские пересказы. */
window.LitPrimary = (() => {
  "use strict";
  const cap = s => String(s || "").replace(/^./, c => c.toUpperCase());
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const rnd = seed => { let h = 2166136261; for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 100000) / 100000; }; };
  const pick = (r, a) => a[Math.floor(r() * a.length)];

  const FRAGMENTS = [
    { text: "У лукоморья дуб зелёный;\nЗлатая цепь на дубе том.", author: "А. С. Пушкин", title: "Руслан и Людмила" },
    { text: "Белая берёза\nПод моим окном\nПринакрылась снегом,\nТочно серебром.", author: "С. А. Есенин", title: "Берёза" },
    { text: "Люблю грозу в начале мая,\nКогда весенний, первый гром,\nКак бы резвяся и играя,\nГрохочет в небе голубом.", author: "Ф. И. Тютчев", title: "Весенняя гроза" },
    { text: "Зима недаром злится,\nПрошла её пора —\nВесна в окно стучится\nИ гонит со двора.", author: "Ф. И. Тютчев", title: "Зима недаром злится" }
  ];

  const GENRES = {
    skazka: { name: "сказка", features: ["есть волшебные предметы", "добро побеждает зло", "троекратный повтор", "зачин и концовка"], works: ["«Колобок»", "«Теремок»", "«Гуси-лебеди»", "«Морозко»"] },
    rasskaz: { name: "рассказ", features: ["реальные события", "один герой и его поступок", "есть завязка и развязка"], works: ["Рассказы Л. Н. Толстого", "Рассказы К. Д. Ушинского"] },
    stih: { name: "стихотворение", features: ["ритм и рифма", "образы и настроение", "строфы и строки"], works: ["«Берёза» С. Есенина", "«Весенняя гроза» Ф. Тютчева"] },
    basnya: { name: "басня", features: ["мораль в конце", "герои-животные", "иносказание"], works: ["Басни И. А. Крылова"] },
    zagadka: { name: "загадка", features: ["описание через признаки", "нужно угадать предмет", "рифма-подсказка"], works: ["Загадки о природе"] },
    poslovica: { name: "пословица", features: ["краткость", "мудрость и вывод", "прямой и переносный смысл"], works: ["Пословицы о труде", "Пословицы о дружбе"] }
  };

  function genreOf(topic) {
    const t = norm(topic);
    if (/сказк|народн|волшеб/.test(t)) return "skazka";
    if (/басн|крылов/.test(t)) return "basnya";
    if (/стих|поэт|пушкин|есенин|тютчев|фет|плещеев|блок/.test(t)) return "stih";
    if (/загадк/.test(t)) return "zagadka";
    if (/пословиц|поговорк/.test(t)) return "poslovica";
    return "rasskaz";
  }

  function answers(genre, grade, seed) {
    const r = rnd(seed), g = +grade, rows = [];
    const add = (q, a) => rows.push({ q, a });
    if (genre === "skazka") {
      add("Какие волшебные предметы помогают героям?", "называет предметы, объясняет их роль");
      add("Кто из героев добрый, а кто злой? Докажи словами из текста.", "характеристика с опорой на текст");
      add("Чему учит сказка?", "добро побеждает зло, нужно помогать другим");
      add("Какие повторы есть в сказке?", "как правило, трёхкратный повтор");
    } else if (genre === "stih") {
      const f = pick(r, FRAGMENTS);
      add(`Прочитай строки и определи настроение: «${f.text.split("\n")[0]}…»`, "настроение радостное/грустное — по словам и ритму");
      add("Найди сравнение или эпитет.", "например, «точно серебром», «белая берёза»");
      add("Что представил, когда слушал стихотворение?", "словесная картинка своими словами");
      add("Сколько строк в строфе?", "по тексту учебника");
    } else if (genre === "basnya") {
      add("Назови героев басни.", "животные или люди по тексту");
      add("Какова мораль басни?", "вывод из последних строк, объяснённый своими словами");
      add("Что высмеивает автор?", "порок, названный в морали");
      add("Какие слова басни стали крылатыми?", "например, «А воз и ныне там»");
    } else if (genre === "zagadka") {
      add("Назови признаки предмета из загадки.", "перечисляет признаки из текста");
      add("Есть ли в загадке рифма?", "да/нет, приводит строки");
      add("Какие загадки о природе ты знаешь?", "называет 1–2 загадки");
    } else if (genre === "poslovica") {
      add("Как ты понимаешь пословицу «Труд кормит, а лень портит»?", "объяснение прямым и переносным смыслом");
      add("Подбери пословицу о дружбе.", "например, «Старый друг лучше новых двух»");
      add("Что общего у пословицы и поговорки?", "краткость, мудрость; поговорка — часть суждения");
    } else {
      add("Кто главный герой? Опиши его по плану.", "имя, внешность, поступки, характер");
      add("Что произошло в начале, в середине и в конце рассказа?", "завязка, кульминация, развязка");
      add("Объясни поступок героя: почему он так сделал?", "мотив с опорой на текст");
      add("Чему учит рассказ?", "главная мысль своими словами");
    }
    if (g <= 2) add("Нарисуй иллюстрацию к самому интересному эпизоду.", "рисунок с подписью");
    else add("Придумай продолжение текста (3–4 предложения).", "творческая работа с сохранением темы");
    return rows;
  }

  function plan(genre) {
    const G = GENRES[genre];
    return [
      "1. Прочитай текст (или послушай чтение учителя).",
      "2. Назови жанр и объясни признаки.",
      "3. Раздели текст на части и озаглавь каждую.",
      "4. Составь план из 3–5 пунктов.",
      "5. Перескажи по плану (кратко/подробно).",
      "6. Найди средства выразительности или слова-помощники.",
      "7. Ответь на вопросы к тексту.",
      "8. Выполни творческое задание."
    ];
  }

  function conspect(p) {
    const g = +p.grade || 1, genre = genreOf(p.topic), G = GENRES[genre], ts = answers(genre, g, p.topic + g);
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, готовность, речевая разминка."],
      ["2", "Речевая разминка", "3–4", `Чистоговорка и дыхательное упражнение. ${genre === "stih" ? "Упражнение на ритм." : "Упражнение на силу голоса."}`],
      ["3", "Подготовка к чтению", "4–5", `Рассматриваем иллюстрацию, прогнозируем содержание, знакомимся с жанром «${G.name}». Признаки: ${G.features.slice(0, 2).join("; ")}.`],
      ["4", "Первичное чтение", "8–10", "Читает учитель, затем дети по абзацам. Остановки для вопросов."],
      ["5", "Физминутка", "2", "Движения под ритм текста."],
      ["6", "Анализ текста", "9–10", `Отвечаем: ${ts.slice(0, 3).map(x => x.q).join("; ")}. Находим средства выразительности, обсуждаем героя.`],
      ["7", "Составление плана и пересказ", "7–8", "Делим текст на части, озаглавливаем, пересказываем по плану."],
      ["8", "Творческая работа", "4–5", ts[ts.length - 1].q],
      ["9", "Итог и рефлексия", "2–3", "Что понравилось? Что было трудно? Чему учит текст?"],
      ["10", "Домашнее задание", "1–2", "Прочитать текст, подготовить пересказ или выучить строки."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const planRows = plan(genre).map((x, i) => `| ${i + 1} | ${x} |`).join("\n");
    const qaT = "| № | Задание/вопрос | Ответ/критерий |\n|---|---|---|\n" + ts.map((x, i) => `| ${i + 1} | ${x.q} | ${x.a} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Литературное чтение · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Формировать умение читать и понимать текст, определять жанр, составлять план и пересказывать; воспитывать интерес к чтению.`,
      "",
      "## Планируемые результаты",
      "**Предметные:** читать осознанно, определять жанр и тему, составлять план, пересказывать, находить средства выразительности.",
      "**Метапредметные:** прогнозировать, сравнивать, объяснять поступки героев, работать в паре.",
      "**Личностные:** интерес к книге, доброжелательность, умение слушать.",
      "",
      "## Опорные знания",
      `Жанр: ${G.name}. Признаки: ${G.features.join("; ")}.`,
      `Примеры: ${G.works.join(", ")}.`,
      "",
      "## Этапы урока",
      table,
      "",
      "## План работы с текстом",
      "| № | Шаг |\n|---|---|\n" + planRows,
      "",
      "## Задания и вопросы с ответами",
      qaT,
      "",
      "## Словарная работа",
      "Выписать 2–3 новых слова, объяснить их значение, составить с ними предложение.",
      "",
      "## Оценивание",
      "Чтение без ошибок, правильные ответы, пересказ по плану, аккуратность и творчество.",
      "",
      "## Домашнее задание",
      "Прочитать текст, подготовить пересказ по плану или выучить строки наизусть."
    ].join("\n");
  }

  function worksheet(p) {
    const g = +p.grade || 1, genre = genreOf(p.topic), G = GENRES[genre], ts = answers(genre, g, p.topic + "ws");
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. До чтения",
      "Рассмотри иллюстрацию. Предположи, о чём текст.",
      "",
      "## 2. Во время чтения",
      "Отметь непонятные слова: ______________________________",
      "",
      "## 3. План текста",
      "1) __________________  2) __________________  3) __________________",
      "",
      "## 4. Вопросы",
      ts.slice(0, 4).map((x, i) => `${i + 1}) ${x.q}`).join("\n"),
      "",
      "## 5. Найди в тексте",
      "Сравнение/эпитет/повтор (подчеркни в книге и выпиши): ____________________",
      "",
      "## 6. Творческое задание",
      ts[ts.length - 1].q,
      "",
      "## 7. Рефлексия",
      "Что понравилось? Что было трудно?"
    ].join("\n");
  }

  return { genreOf, answers, conspect, worksheet, lesson: conspect, GENRES };
})();
