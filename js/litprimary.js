/* «Учу по ФРП» — литературное чтение 1–4 классов без нейросети.
   Задания в формате рабочих тетрадей и учебников: чтение, вопросы, план,
   пересказ, выразительное чтение, средства выразительности, творческая работа.
   Тексты — общественное достояние или краткие авторские пересказы. */
window.LitPrimary = (() => {
  "use strict";
  const cap = s => String(s || "").replace(/^./, c => c.toUpperCase());
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const rnd = seed => { let h = 2166136261; for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 100000) / 100000; }; };
  const pick = (r, a) => a[Math.floor(r() * a.length)];

  const FRAGMENTS = [
    { text: "У лукоморья дуб зелёный;\nЗлатая цепь на дубе том.", author: "А. С. Пушкин", title: "Руслан и Людмила" },
    { text: "Белая берёза\nПод моим окном\nПринакрылась снегом,\nТочно серебром.", author: "С. А. Есенин", title: "Берёза" },
    { text: "Люблю грозу в начале мая,\nКогда весенний, первый гром,\nКак бы резвяся и играя,\nГрохочет в небе голубом.", author: "Ф. И. Тютчев", title: "Весенняя гроза" },
    { text: "Зима недаром злится,\nПрошла её пора —\nВесна в окно стучится\nИ гонит со двора.", author: "Ф. И. Тютчев", title: "Зима недаром злится" }
  ];

  const GENRES = {
    skazka: { name: "сказка", features: ["повествование о вымышленных событиях", "волшебство характерно для волшебных сказок", "повторы, зачин и концовка часто встречаются в народных сказках"], works: ["«Колобок»", "«Теремок»", "«Гуси-лебеди»", "«Морозко»"] },
    rasskaz: { name: "рассказ", features: ["небольшой объём", "одно или несколько связанных событий — реальных или вымышленных", "герои, их поступки и переживания"], works: ["Рассказы Л. Н. Толстого", "Рассказы К. Д. Ушинского"] },
    stih: { name: "стихотворение", features: ["речь организована стихотворными строками", "образы и настроение", "ритм и звучание; рифма и строфы есть не во всех стихотворениях"], works: ["«Берёза» С. Есенина", "«Весенняя гроза» Ф. Тютчева"] },
    basnya: { name: "басня", features: ["иносказательный поучительный рассказ", "герои — люди, животные или предметы", "мораль может быть в начале, в конце или подразумеваться"], works: ["Басни И. А. Крылова"] },
    zagadka: { name: "загадка", features: ["описание через признаки", "нужно отгадать предмет или явление", "рифма может помогать, но не обязательна"], works: ["Загадки о природе"] },
    poslovica: { name: "пословица", features: ["краткость", "мудрость и вывод", "прямой и переносный смысл"], works: ["Пословицы о труде", "Пословицы о дружбе"] }
  };

  function genreOf(topic) {
    const t = norm(topic);
    if (/сказк|народн|волшеб/.test(t)) return "skazka";
    if (/басн|крылов/.test(t)) return "basnya";
    if (/стих|поэт|пушкин|есенин|тютчев|фет|плещеев|блок/.test(t)) return "stih";
    if (/загадк/.test(t)) return "zagadka";
    if (/пословиц|поговорк/.test(t)) return "poslovica";
    return "rasskaz";
  }

  function answers(genre, grade, seed) {
    const r = rnd(seed), g = +grade, rows = [];
    const add = (q, a) => rows.push({ q, a });
    if (genre === "skazka") {
      add("Кто или что помогло герою? Найди эпизод и покажи, что изменилось.", "называет героя, предмет или поступок; объясняет результат, опираясь на эпизод");
      add("Выбери поступок героя. Как бы ты его оценил? Найди слова, которые помогают это объяснить.", "характеристика с опорой на текст");
      add("Чему учит сказка?", "вывод ученика согласуется с поступком героя и его последствием");
      add("Повторяются ли в сказке слова или эпизоды? Найди пример или объясни, как развивается действие без повтора.", "сопоставляет два похожих момента или называет последовательность разных событий");
    } else if (genre === "stih") {
      const f = pick(r, FRAGMENTS);
      add(`Для тренировки прочитай фрагмент (${f.author}, «${f.title}»): «${f.text.replace(/\n/g, " / ")}» Какое чувство он вызывает? Назови слово, которое подсказало ответ.`, "называет чувство и указывает слово из приведённого фрагмента; возможны разные обоснованные ответы");
      add("Теперь вернись к стихотворению урока. Выбери слово или выражение, которое помогло представить картину. Что именно ты представил?", "приводит выражение именно из изучаемого стихотворения и поясняет его действие");
      add("Что представил, когда слушал стихотворение?", "словесная картинка своими словами");
      add("Сколько строк в строфе?", "считает стихотворные строки в выбранной строфе; перенос длинной строки при печати не образует новую строку стиха");
    } else if (genre === "basnya") {
      add("Назови героев басни.", "животные или люди по тексту");
      add("Какова мораль басни?", "формулирует вывод своими словами и связывает его с поступком и последствием; мораль может стоять в начале, в конце или подразумеваться");
      add("Что высмеивает автор?", "порок, названный в морали");
      add("Какая реплика или строка помогает понять басню? Прочитай её и объясни свой выбор.", "точная строка из прочитанной басни и пояснение, как она связана с поступком героя");
    } else if (genre === "zagadka") {
      add("Назови признаки предмета из загадки.", "перечисляет признаки из текста");
      add("Есть ли в загадке рифма?", "да/нет, приводит строки");
      add("Какие загадки о природе ты знаешь?", "называет 1–2 загадки");
    } else if (genre === "poslovica") {
      add("Как ты понимаешь пословицу «Труд кормит, а лень портит»?", "объяснение прямым и переносным смыслом");
      add("Подбери пословицу о дружбе.", "например, «Старый друг лучше новых двух»");
      add("Что общего у пословицы и поговорки?", "краткость, мудрость; поговорка — часть суждения");
    } else {
      add("Кто главный герой? Опиши его по плану.", "имя, внешность, поступки, характер");
      add("Что произошло в начале, в середине и в конце рассказа?", "завязка, кульминация, развязка");
      add("Объясни поступок героя: почему он так сделал?", "мотив с опорой на текст");
      add("Чему учит рассказ?", "главная мысль своими словами");
    }
    if (g <= 2) add("Нарисуй иллюстрацию к самому интересному эпизоду.", "рисунок с подписью");
    else add("Придумай продолжение текста (3–4 предложения).", "творческая работа с сохранением особенностей героя или настроения стихотворения");
    return rows;
  }

  function plan(genre) {
    const G = GENRES[genre];
    return [
      "1. Прочитай текст (или послушай чтение учителя).",
      "2. Назови жанр и объясни признаки.",
      "3. Раздели текст на части и озаглавь каждую.",
      "4. Составь план из 3–5 пунктов.",
      "5. Перескажи по плану (кратко/подробно).",
      "6. Найди средства выразительности или слова-помощники.",
      "7. Ответь на вопросы к тексту.",
      "8. Выполни творческое задание."
    ];
  }

  const speechTopic = p => /предложен[а-я]* из речевого потока|устная и письменная речь/.test(norm(p.topic));
  const speechTasks = [
    ["Послушай: «Утром шёл дождь. Потом выглянуло солнце». Сколько предложений ты услышал?", "Два предложения. Между ними слышна пауза."],
    ["Покажи, где заканчивается первое предложение: Утром шёл дождь. Потом выглянуло солнце.", "После слова «дождь» стоит точка."],
    ["Запиши два предложения: светит солнце гуляют дети", "Светит солнце. Гуляют дети."],
    ["Когда мы рассказываем вслух, а когда пишем записку, какой речью пользуемся?", "Рассказ вслух — устная речь. Записка — письменная речь."]
  ];
  const speechRule = "В устной речи конец предложения слышен по интонации и паузе. На письме предложение начинается с заглавной буквы. В конце законченного сообщения ставим точку.";
  function speechConspect(p) {
    const [listen, mark, write, tell] = speechTasks;
    const prev = typeof previousTopicFor === "function" ? previousTopicFor(p) : "";
    const review = prev ? `Что из темы «${prev}» помогает слушать и понимать друг друга?` : "Как понять, что говорящий закончил свою мысль?";
    return [`# ${p.topic}`, "", "## Этапы урока", "",
      "| Этап | Время | Учитель | Ученики |", "|---|---|---|---|",
      `| Короткое повторение | ${Math.min(3, Math.floor((p.duration || 45) / 10))} | ${review} | Дают один ответ и слушают пример. |`,
      `| Наблюдаем за устной речью | 7 | ${listen[0]} ${listen[1]} | Отмечают паузу хлопком. |`,
      `| Находим границу на письме | 9 | ${speechRule} ${mark[0]} Ответ: ${mark[1]} | Показывают точку и заглавную букву в начале второго предложения. |`,
      `| Сравниваем устную и письменную речь | 8 | ${tell[0]} Ответ: ${tell[1]} | Сравнивают произнесённое предложение с записанным. |`,
      `| Записываем сами | 12 | ${write[0]}. После работы покажите образец: ${write[1]} | Делят запись на два предложения, сверяют заглавные буквы и точки. |`,
      "| Подводим итог | 4 | По каким признакам узнаём конец предложения на слух и на письме? | Называют паузу и точку. |",
      "| Домашнее задание | 2 | Запиши два коротких предложения о погоде, отметь точки. | Записывают задание. |", ""].join("\n");
  }

  function cards(p) {
    if (!speechTopic(p)) return null;
    return [
      { kind: "title", title: p.topic, points: [`${p.grade} класс · Литературное чтение`] },
      { kind: "big", title: "Где пауза?", lead: "Утром шёл дождь. Потом выглянуло солнце.", notes: speechTasks[0].join(" ") },
      { kind: "list", title: "Предложение устно и на письме", points: ["На слух — интонация и пауза.", "На письме — заглавная буква в начале и точка в конце сообщения."] },
      { kind: "check", title: "Проверим себя", points: speechTasks.slice(1).map(([q]) => q), answers: speechTasks.slice(1).map(([, a]) => a) },
      { kind: "hw", title: "Домашнее задание", points: ["Запиши два предложения о погоде и отметь точки."] }
    ].map((card, i) => ({ id: `speech-${i}`, on: true, ...card }));
  }

  function conspect(p) {
    if (speechTopic(p)) return speechConspect(p);
    const g = +p.grade || 1, genre = genreOf(p.topic), G = GENRES[genre], ts = answers(genre, g, p.topic + g);
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, готовность, речевая разминка."],
      ["2", "Короткое повторение", String(Math.min(3, Math.floor((p.duration || 45) / 10))), "Какой приём прошлого урока поможет нам понять новый текст?"],
      ["3", "Подготовка к чтению", "4–5", `Рассматриваем иллюстрацию, прогнозируем содержание, знакомимся с жанром «${G.name}». Признаки: ${G.features.slice(0, 2).join("; ")}.`],
      ["4", "Первичное чтение", "8–10", "Читает учитель, затем дети по абзацам. Остановки для вопросов."],
      ["5", "Физминутка", "2", "Движения под ритм текста."],
      ["6", "Анализ текста", "9–10", `Отвечаем: ${ts.slice(0, 3).map(x => x.q).join("; ")}. Находим средства выразительности, обсуждаем героя.`],
      ["7", "Составление плана и пересказ", "7–8", "Делим текст на части, озаглавливаем, пересказываем по плану."],
      ["8", "Творческая работа", "4–5", ts[ts.length - 1].q],
      ["9", "Итог и рефлексия", "2–3", "Что понравилось? Что было трудно? Чему учит текст?"],
      ["10", "Домашнее задание", "1–2", "Прочитать текст, подготовить пересказ или выучить строки."]
    ];
    const students = ["Готовятся к чтению.", "Называют один знакомый приём.", "Прогнозируют содержание.", "Слушают, читают и отмечают непонятные слова.", "Выполняют разминку.", "Отвечают, ссылаясь на текст.", "Озаглавливают части и пересказывают.", "Выполняют творческое задание.", "Формулируют вывод.", "Записывают задание."];
    const table = "| № | Этап урока | Время | Учитель | Ученики |\n|---|---|---|---|---|\n" + rows.map((r, i) => `| ${[...r, students[i]].join(" | ")} |`).join("\n");
    const planRows = plan(genre).map((x, i) => `| ${i + 1} | ${x} |`).join("\n");
    const qaT = "| № | Задание/вопрос | Ответ/критерий |\n|---|---|---|\n" + ts.map((x, i) => `| ${i + 1} | ${x.q} | ${x.a} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Литературное чтение · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Формировать умение читать и понимать текст, определять жанр, составлять план и пересказывать; воспитывать интерес к чтению.`,
      "",
      "## Планируемые результаты",
      "**Предметные:** читать осознанно, определять жанр и тему, составлять план, пересказывать, находить средства выразительности.",
      "**Метапредметные:** прогнозировать, сравнивать, объяснять поступки героев, работать в паре.",
      "**Личностные:** интерес к книге, доброжелательность, умение слушать.",
      "",
      "## Опорные знания",
      `Жанр: ${G.name}. Признаки: ${G.features.join("; ")}.`,
      `Примеры: ${G.works.join(", ")}.`,
      "",
      "## Этапы урока",
      table,
      "",
      "## План работы с текстом",
      "| № | Шаг |\n|---|---|\n" + planRows,
      "",
      "## Задания и вопросы с ответами",
      qaT,
      "",
      "## Словарная работа",
      "Выписать 2–3 новых слова, объяснить их значение, составить с ними предложение.",
      "",
      "## Оценивание",
      "Чтение без ошибок, правильные ответы, пересказ по плану, аккуратность и творчество.",
      "",
      "## Домашнее задание",
      "Прочитать текст, подготовить пересказ по плану или выучить строки наизусть."
    ].join("\n");
  }

  function worksheet(p) {
    if (speechTopic(p)) return [`# Рабочий лист: ${p.topic}`, "", `**Класс:** ${p.grade} · **Имя:** ______________________`, "",
      ...speechTasks.flatMap(([q], i) => [`### Задание ${i + 1}`, q, "", "[ ________________________________________ ]", ""])
    ].join("\n");
    const g = +p.grade || 1, genre = genreOf(p.topic), G = GENRES[genre], ts = answers(genre, g, p.topic + "ws");
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. До чтения",
      "Прочитай заглавие или послушай его. Если есть иллюстрация, рассмотри её. Как ты думаешь, о чём пойдёт речь?",
      "",
      "## 2. Во время чтения",
      "Отметь непонятные слова: ______________________________",
      "",
      "## 3. План текста",
      "1) __________________  2) __________________  3) __________________",
      "",
      "## 4. Вопросы",
      ts.slice(0, 4).map((x, i) => `${i + 1}) ${x.q}`).join("\n"),
      "",
      "## 5. Найди в тексте",
      "Выпиши слово, выражение или повтор, который помогает представить картину: ____________________",
      "",
      "## 6. Творческое задание",
      ts[ts.length - 1].q,
      "",
      "## 7. Рефлексия",
      "Что понравилось? Что было трудно?"
    ].join("\n");
  }

  return { genreOf, answers, conspect, worksheet, cards, lesson: conspect, GENRES };
})();
