/* «Учу по ФРП» — математика 1–4 классов без нейросети.
   Собирает конспект, технологическую карту и рабочий лист по теме урока
   из возрастных опор: устный счёт, объяснение, примеры, задания, проверка.
   Все примеры генерируются по правилам класса; ответы прилагаются. */
window.MathPrimary = (() => {
  "use strict";
  const rnd = seed => { let h = 2166136261; for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 100000) / 100000; }; };
  const ri = (r, a, b) => a + Math.floor(r() * (b - a + 1));
  const cap = s => String(s || "").replace(/^./, c => c.toUpperCase());
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const MAX = g => (+g === 1 ? 10 : +g === 2 ? 20 : +g === 3 ? 100 : 1000);

  function kindOf(topic) {
    const t = norm(topic);
    if (/умнож|делен|таблиц.*умнож/.test(t)) return "muldiv";
    if (/дроб|дол[яи]|процент/.test(t)) return "frac";
    if (/уравнен|буквенн|выражени/.test(t)) return "equation";
    if (/движени|скорост|время в пути|расстоян/.test(t)) return "motion";
    if (/задач|цена|стоимост|работа/.test(t)) return "word";
    if (/периметр|площад|фигур|треугольник|прямоугольник|круг|угол|отрезок|длина/.test(t)) return "geom";
    if (/величин|метр|килограмм|литр|час|врем|масса|сравнен/.test(t)) return "size";
    if (/слож|вычита|счет|числ|разряд|десяток|нумерац/.test(t)) return "addsub";
    return "numbers";
  }

  function explain(kind, grade) {
    const g = +grade;
    const blocks = {
      numbers: ["Число показывает количество предметов.", "Цифра — знак для записи числа.", "Сравниваем: больше, меньше, равно.", "Соседи числа: на 1 больше и на 1 меньше."],
      addsub: ["Сложение — объединение групп.", "Вычитание — узнаём, сколько осталось или на сколько больше.", "Проверка: сложение проверяем вычитанием, вычитание — сложением.", "Считаем по частям: десятки отдельно, единицы отдельно."],
      muldiv: ["Умножение — сложение одинаковых слагаемых.", "Деление — узнаём, сколько раз одно число содержится в другом.", "Таблица умножения — основа быстрого счёта.", "Проверка: деление проверяем умножением."],
      motion: ["Скорость — сколько метров/километров за единицу времени.", "Расстояние = скорость × время.", "Время = расстояние : скорость.", "Скорость = расстояние : время.", "Проверяем единицы: км/ч, м/с, ч, мин."],
      word: ["У задачи есть условие, вопрос, решение и ответ.", "Краткая запись помогает увидеть данные.", "Выбираем действие по смыслу вопроса.", "Проверяем ответ по смыслу и обратным действием."],
      size: ["Величины измеряют: длина, масса, время, объём.", "Единицы связаны: 1 м = 100 см, 1 кг = 1000 г, 1 ч = 60 мин.", "Переводим единицы перед вычислением.", "Сравниваем только одинаковые единицы."],
      geom: ["Фигуры различаем по числу сторон и углов.", "Периметр — сумма длин сторон.", "Площадь прямоугольника = длина × ширина.", "Чертёж выполняем по линейке и подписываем размеры."],
      frac: ["Доля — равная часть целого.", "Числитель показывает, сколько частей взяли.", "Знаменатель — на сколько частей разделили.", "Сравниваем доли: чем больше знаменатель, тем меньше доля."],
      equation: ["Уравнение — равенство с неизвестным.", "Находим неизвестное обратным действием.", "Проверка: подставить ответ в уравнение.", "Проговариваем правило вслух."]
    };
    return blocks[kind] || blocks.numbers;
  }

  function tasks(kind, grade, seed) {
    const r = rnd(seed), m = MAX(grade), out = [];
    const answer = (q, a) => ({ q, a });
    for (let i = 0; i < 6; i++) {
      if (kind === "addsub" || kind === "numbers") {
        const a = ri(r, 1, m), b = ri(r, 1, Math.max(2, Math.floor(m / 2)));
        if (i % 2 === 0) out.push(answer(`${a} + ${b} = ?`, `${a + b}`));
        else { const big = Math.max(a, b), sm = Math.min(a, b); out.push(answer(`${big} − ${sm} = ?`, `${big - sm}`)); }
      } else if (kind === "muldiv") {
        const a = ri(r, 2, 9), b = ri(r, 2, 9);
        if (i % 2 === 0) out.push(answer(`${a} × ${b} = ?`, `${a * b}`));
        else out.push(answer(`${a * b} : ${a} = ?`, `${b}`));
      } else if (kind === "motion") {
        const v = ri(r, 2, 9), tm = ri(r, 2, 6);
        if (i % 3 === 0) out.push(answer(`Скорость ${v} км/ч, время ${tm} ч. Какое расстояние?`, `${v * tm} км`));
        else if (i % 3 === 1) out.push(answer(`Расстояние ${v * tm} км, скорость ${v} км/ч. Сколько времени?`, `${tm} ч`));
        else out.push(answer(`Расстояние ${v * tm} км за ${tm} ч. Какая скорость?`, `${v} км/ч`));
      } else if (kind === "word") {
        const a = ri(r, 2, Math.max(3, Math.floor(m / 3))), b = ri(r, 1, Math.max(2, Math.floor(m / 3)));
        const names = [["яблоки", "яблок"], ["карандаши", "карандашей"], ["книги", "книг"], ["мячи", "мячей"]];
        const w = names[i % names.length];
        if (i % 2 === 0) out.push(answer(`В корзине ${a} ${w[1]}, положили ещё ${b}. Сколько стало?`, `${a + b} ${w[1]}`));
        else out.push(answer(`Было ${a + b} ${w[1]}, взяли ${b}. Сколько осталось?`, `${a} ${w[1]}`));
      } else if (kind === "size") {
        const a = ri(r, 1, 9), b = ri(r, 1, 9);
        if (i % 2 === 0) out.push(answer(`${a} м = ? см`, `${a * 100} см`));
        else out.push(answer(`${a} кг ${b * 100} г = ? г`, `${a * 1000 + b * 100} г`));
      } else if (kind === "geom") {
        const a = ri(r, 2, 9), b = ri(r, 2, 9);
        if (i % 2 === 0) out.push(answer(`Периметр прямоугольника ${a} см и ${b} см`, `${2 * (a + b)} см`));
        else out.push(answer(`Площадь прямоугольника ${a} см и ${b} см`, `${a * b} см²`));
      } else if (kind === "frac") {
        const n = [2, 3, 4, 5][i % 4];
        out.push(answer(`Найди 1/${n} от ${n * 6}`, `${6}`));
      } else {
        const a = ri(r, 1, 9), b = ri(r, 1, 9);
        if (i % 2 === 0) out.push(answer(`x + ${a} = ${a + b}. Найди x`, `${b}`));
        else out.push(answer(`${a + b} − x = ${a}. Найди x`, `${b}`));
      }
    }
    return out;
  }

  const stage = (name, mins, what) => `${name} (${mins} мин). ${what}`;

  function conspect(p, type) {
    const g = +p.grade, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + g);
    const skills = ["считать и записывать числа", "решать примеры и задачи по теме", "проверять результат", "объяснять ход решения"];
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, проверка готовности, настрой на работу."],
      ["2", "Устный счёт", "4–5", `Игра «Сосчитай быстро»: ${ts.slice(0, 2).map(x => x.q.replace("= ?", "")).join("; ")}. Дети считают вслух, проверяют ответы.`],
      ["3", "Новое знание", "8–10", `${cap(p.topic)}. Объяснение по шагам: ${explain(kind, g).slice(0, 2).join(" ")} Работа с наглядностью: карточки, числовая прямая, счётный материал.`],
      ["4", "Первичное закрепление", "8–10", `Решаем вместе у доски: ${ts.slice(2, 4).map(x => x.q + " (" + x.a + ")").join("; ")}. Проговариваем каждый шаг.`],
      ["5", "Физминутка", "2", "Движения под счёт: хлопки, шаги, наклоны — смена деятельности."],
      ["6", "Самостоятельная работа", "6–8", `По карточкам: ${ts.slice(4).map(x => x.q).join("; ")}. Самопроверка по образцу.`],
      ["7", "Повторение и итог", "3–4", "Что узнали? Что было трудно? Проговариваем правило своими словами."],
      ["8", "Домашнее задание", "1–2", "Решить 3 примера и одну задачу по теме; повторить правило."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const taskTable = "| № | Задание | Ответ |\n|---|---|---|\n" + ts.map((x, i) => `| ${i + 1} | ${x.q} | ${x.a} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Математика · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Формировать умение по теме «${p.topic}» и применять его при решении примеров и задач.`,
      "",
      "## Планируемые результаты",
      `**Предметные:** ${skills.join("; ")}.`,
      "**Метапредметные:** сравнивать, находить закономерность, проверять результат, работать в паре.",
      "**Личностные:** интерес к математике, аккуратность, уверенность в своих силах.",
      "",
      "## Опорные знания класса",
      explain(kind, g).map(x => "- " + x).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Примеры и задания с ответами",
      taskTable,
      "",
      "## Оценивание",
      "Верно решено больше половины заданий — «хорошо»; без ошибок и с объяснением — «отлично»; ошибки разбираем и исправляем.",
      "",
      "## Домашнее задание",
      `Учебник: тема «${p.topic}»; решить 3 примера и одну задачу, повторить правило.`
    ].join("\n");
  }

  function worksheet(p) {
    const g = +p.grade, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + "ws" + g);
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. Устный счёт",
      ts.slice(0, 3).map((x, i) => `${i + 1}) ${x.q}`).join("   "),
      "",
      "## 2. Вспомни правило",
      explain(kind, g).slice(0, 2).map(x => "- " + x).join("\n"),
      "",
      "## 3. Реши по образцу",
      ts.slice(3, 5).map((x, i) => `${i + 1}) ${x.q}`).join("   "),
      "",
      "## 4. Задача",
      ts[5] ? ts[5].q : "Составь свою задачу по теме и реши её.",
      "",
      "## 5. Проверь себя",
      "Сравни с ответами учителя. Отметь: ✓ — верно, ? — было трудно.",
      "",
      "## 6. Рефлексия",
      "Что получилось? Что нужно повторить?"
    ].join("\n");
  }

  function lesson(p) { return conspect(p, { name: "Урок открытия нового знания" }); }

  return { kindOf, tasks, explain, conspect, worksheet, lesson };
})();
