      const used = new Set([...(p.exFull || []).map(e => e.text.slice(0, 60)), p.hwText?.exText ? p.hwText.exText.slice(0, 60) : ""]);
      const pool = ru ? pickEx(p, materials, C.n * variants * 2 + 4).filter(e => !used.has(e.text.slice(0, 60))) : [];
