  function splitMinutes(stages, total, ru) {
    // вес этапа — по его названию (до двоеточия): открытие и практика длиннее, организационные и подводящие этапы короче
    const head = st => st.split(":")[0];
    const disc = st => /реализац|открыти|изучени|анализ|аналит|работа над темой/i.test(head(st));
    const w = stages.map(st => { const s = head(st); return disc(st) ? 5.5 : /информацион|закреплен|контрольн|комментари|чтени[A-Za-z0-9_А-Яа-яЁё]* эпизод|создание собственного/i.test(s) ? 5 : /самостоятел/i.test(s) ? 4.5 : /^творческ/i.test(s) ? 2.5 : /рефлекс|домашн|постановк/i.test(s) ? 1 : /построен/i.test(s) ? 1 : /организац/i.test(s) ? 1 : /мотивац|актуализ|пробн/i.test(s) ? 1.6 : /выявлен/i.test(s) ? 1.3 : 2; });
    const sum = w.reduce((a, b) => a + b, 0);
    const mins = w.map(x => Math.max(1, Math.round(x / sum * total)));
    let diff = total - mins.reduce((a, b) => a + b, 0), i = mins.indexOf(Math.max(...mins));
    mins[i] += diff;
    /* русский язык: на практику (закрепление, самостоятельная работа, включение, проверка) – не меньше 45% урока;
       минуты берутся из подводящих этапов, но не из открытия правила (не меньше 9 минут при 45) */
    if (ru) {
      const pr = stages.map(st => /закреплен|самостоятел|практик|тренинг|применен|контрольн|включени|создание собственного|трансформац|классификац|редактирован|взаимопроверк|творческ|работа над ошибк|самоконструкц|социоконструкц|социализац|афиширован/i.test(head(st)));
      const floor = st => disc(st) ? Math.round(total * 0.2) : /рефлекс|организац|домашн|постановк|построен/i.test(head(st)) ? 1 : 3;
      if (pr.some(Boolean) && pr.some(x => !x)) {
        let guard = 60;
        while (guard-- > 0 && mins.reduce((a, m, k) => a + (pr[k] ? m : 0), 0) < Math.ceil(total * 0.45)) {
          let from = -1; mins.forEach((m, k) => { if (!pr[k] && m > floor(stages[k]) && (from < 0 || m - floor(stages[k]) > mins[from] - floor(stages[from]))) from = k; });
          if (from < 0) break;
          let to = -1; mins.forEach((m, k) => { if (pr[k] && (to < 0 || m < mins[to])) to = k; });
          mins[from]--; mins[to]++;
        }
      }
    }
    return mins;
  }
