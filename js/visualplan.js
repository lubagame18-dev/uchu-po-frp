  const SVG_ALLOWED_CHARS = new Set("ABCDEFMNPQRSTUIVWxyzαβγδθλμπσφωΔΩ+−=·×°%<>".split(""));
  const SVG_SIGNS = new Set(["+", "−", "=", "·", "×", "°", "%", "<", ">"]);

  function attrMap(attrs) {
    const out = {};
    const re = /([A-Za-z_:][A-Za-z0-9_:.-]*)\s*=\s*(?:"([^"]*)"|'([^']*)')/g;
    let m;
    while ((m = re.exec(attrs)) !== null) out[m[1].toLowerCase()] = m[2] != null ? m[2] : m[3];
    return out;
  }

  function tagList(markup) {
    const out = [];
    const re = /<([A-Za-z][A-Za-z0-9:_-]*)((?:"[^"]*"|'[^']*'|[^>"'])*)>/g;
    let m;
    while ((m = re.exec(markup)) !== null) out.push({ name: m[1].toLowerCase(), attrs: attrMap(m[2] || ""), raw: m[0] });
    return out;
  }

  function textContentOf(markup) {
    return String(markup || "").replace(/<[^>]*>/g, " ");
  }

  function validateSvgMarkup(markup, path, add) {
    if (typeof markup !== "string" || !markup.trim()) {
      add("SVG_MISSING", path, "svg_markup пуст");
      return;
    }
    const src = markup.trim();
    const startsSvg = /^<svg[\s>]/i.test(src);
    const rightViewBox = /viewBox\s*=\s*["']\s*0\s+0\s+800\s+600\s*["']/i.test(src);
    const closed = /<\/svg>\s*$/i.test(src);
    if (!startsSvg || !rightViewBox) {
      add("SVG_INVALID", path, "SVG должен начинаться с <svg и иметь viewBox=\"0 0 800 600\"");
    } else if (!closed) {
      add("SVG_INVALID", path, "SVG не закрыт");
    }
    if (src.indexOf("#F8FAFC") < 0) add("SVG_NO_BACKGROUND", path, "нет светлого фона #F8FAFC");

    const tags = tagList(src);
    const elements = tags.filter(t => t.name !== "svg");
    if (elements.length > 12) add("SVG_TOO_MANY_ELEMENTS", path + ".svg_markup", "элементов больше 12: " + elements.length);

    const plain = textContentOf(src);
    if (/[А-Яа-яЁё]/.test(plain)) add("SVG_HAS_WORDS", path + ".svg_markup", "в тексте SVG есть кириллица");
    if (/[0-9]/.test(plain)) add("SVG_HAS_WORDS", path + ".svg_markup", "в тексте SVG есть цифры");
    const words = plain.match(/[A-Za-z]+/g) || [];
    for (const word of words) {
      if (word.length === 1 && SVG_ALLOWED_CHARS.has(word)) continue;
      add("SVG_HAS_WORDS", path + ".svg_markup", "в тексте SVG латинское слово: " + word);
      break;
    }
    for (const ch of plain.replace(/[A-Za-z0-9А-Яа-яЁё\s]/g, "")) {
      if (SVG_ALLOWED_CHARS.has(ch) || SVG_SIGNS.has(ch)) continue;
      add("SVG_HAS_WORDS", path + ".svg_markup", "недопустимый символ в тексте SVG: " + ch);
      break;
    }

    const vertices = [];
    const isBackground = el => {
      const fill = (el.attrs.fill || "").toUpperCase();
      return fill === "#F8FAFC" || (el.attrs.width && Number(el.attrs.width) >= 640 && fill !== "");
    };
    let boundsError = false;
    const checkPoint = (x, y) => {
      if (!Number.isFinite(x) || !Number.isFinite(y)) return;
      if (x < 120 || x > 680 || y < 100 || y > 500) boundsError = true;
    };
    for (const el of elements) {
      if (el.name === "text") continue;
      const a = el.attrs;
      if (!isBackground(el)) {
        for (const key of ["x", "cx", "x1", "x2"]) {
          if (a[key] != null && a[key] !== "") {
            const v = Number(a[key]);
            const paired = key === "x" ? Number(a.y) : key === "cx" ? Number(a.cy) : key === "x1" ? Number(a.y1) : Number(a.y2);
            checkPoint(v, paired);
          }
        }
        for (const key of ["y", "cy", "y1", "y2"]) {
          if (a[key] == null || a[key] === "") continue;
          if ([`x${key.slice(1)}`, "cx"].some(k => a[k] != null && a[k] !== "")) continue;
          const v = Number(a[key]);
          if (!Number.isFinite(v) || (v >= 100 && v <= 500)) continue;
          boundsError = true;
        }
        if (a.points) {
          const nums = String(a.points).split(/[\s,]+/).map(Number).filter(Number.isFinite);
          for (let i = 0; i + 1 < nums.length; i += 2) checkPoint(nums[i], nums[i + 1]);
        }
      }
      if (el.name === "circle") vertices.push([Number(a.cx), Number(a.cy)]);
      if (el.name === "polygon" || el.name === "polyline") {
        const nums = String(a.points || "").split(/[\s,]+/).map(Number).filter(Number.isFinite);
        for (let i = 0; i + 1 < nums.length; i += 2) vertices.push([nums[i], nums[i + 1]]);
      }
      if (el.name === "line") {
        vertices.push([Number(a.x1), Number(a.y1)]);
        vertices.push([Number(a.x2), Number(a.y2)]);
      }
    }
    if (boundsError) add("SVG_OUT_OF_BOUNDS", path + ".svg_markup", "элементы выходят за x∈[120,680], y∈[100,500]");

    for (const el of elements) {
      if (el.name !== "text") continue;
      const tx = Number(el.attrs.x);
      const ty = Number(el.attrs.y);
      if (!Number.isFinite(tx) || !Number.isFinite(ty)) continue;
      let tooClose = false;
      for (const v of vertices) {
        if (!Number.isFinite(v[0]) || !Number.isFinite(v[1])) continue;
        const dx = v[0] - tx, dy = v[1] - ty;
        if (dx * dx + dy * dy < 400) { tooClose = true; break; }
      }
      if (tooClose) add("SVG_TEXT_ON_VERTEX", path + ".svg_markup", "подпись ближе 20 px к вершине/центру");
    }
  }

