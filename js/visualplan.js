  /* Строгая проверка атрибуции произведения (v1.2.1 п.6, уточнение v1.2 final):
     статья/картина допускается только при ТОЧНОМ совпадении названия:
     - название в «ёлочках» темы/слайда равно названию статьи (скобочный уточнитель
       «(повесть)», «(картина ...)» не мешает);
     - либо тема/слайд целиком называет произведение;
     - либо это точная фраза без «ёлочек» при art-слове в теме/слайде
       (например, «Русские богатыри в изобразительном искусстве»).
     Совпадение фрагмента более длинного названия — чужая атрибуция:
     «Солдатская шинель» (народная сказка) ≠ «Шинель» (повесть Гоголя),
     «8 Марта» (праздник) ≠ «Март» (картина Левитана). */
  function titleGrounded(topicText, slideText, quotedTitle, registryTitle) {
    const base = baseTitle(registryTitle);
    if (!base) return false;
    if (quotedTitle && baseTitle(quotedTitle) === base) return true;
    const text = [topicText, slideText].filter(Boolean).join(" ");
    const quotes = allQuoted(text);
    if (quotes.some(q => baseTitle(q) === base)) return true;
    /* Название найдено как фрагмент другого названия в «ёлочках» — не наше. */
    for (const q of quotes) {
      const qb = baseTitle(q);
      if (qb && qb !== base && (qb.indexOf(base) >= 0 || base.indexOf(qb) >= 0)) return false;
    }
    if (norm(topicText) === base || norm(slideText) === base) return true;
    if (ART_WORD.test(text) && (exactPhraseInText(topicText, base) || exactPhraseInText(slideText, base))) return true;
    return false;
  }

