  /* Фразовый матч по целым словам (без «смартфоны» → «март» и подобных подстрок). */
  function phraseMatches(normText, phrase) {
    const hay = String(normText || "").split(" ").filter(Boolean);
    const needle = norm(phrase).split(" ").filter(Boolean);
    if (!hay.length || !needle.length) return false;
    for (let i = 0; i + needle.length <= hay.length; i++) {
      let ok = true;
      for (let j = 0; j < needle.length; j++) {
        const w = needle[j];
        const cand = hay[i + j];
        if (cand === w) continue;
        if (cand.startsWith(w) && cand.length - w.length > 0 && cand.length - w.length <= 3) continue;
        ok = false;
        break;
      }
      if (ok) return true;
    }
    return false;
  }

