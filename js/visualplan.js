  function classifyTopic(rawText, subject) {
    const t = norm(rawText);
    if (!t) return "abstract";
    const code = subjectCode(subject);
    let strong = null;
    let strongIdx = -1;
    for (const entry of GROUNDED_OBJECTS) {
      if (entry.subj && entry.subj.indexOf(code) < 0) continue;
      entry.re.lastIndex = 0;
      const m = entry.re.exec(t);
      if (m) { strong = entry; strongIdx = m.index; break; }
    }
    const grpIdx = firstRegexIndex(GROUP_RE, t);
    const absIdx = firstRegexIndex(ABSTRACT_RE, t);
    if (grpIdx >= 0 && (strongIdx < 0 || grpIdx <= strongIdx) && !(absIdx >= 0 && absIdx < grpIdx)) return "group";
    if (strong) {
      /* v1.2 final (согласовано с независимым аудитом): абстрактное слово
         в теме делает её процессной, даже если предмет назван позже
         («Воздух. Кислород. Понятие об оксидах» → abstract). Предметная тема
         остаётся только если объект стоит в начале («Клетка как система»)
         или перед ним структурная рамка («Строение клетки», «Химический
         состав клетки»), и аудит знает этот предмет. */
      const startsWithStrong = strongIdx === 0;
      const prefix = t.slice(0, strongIdx);
      const structurePrefix = /(?:^| )(?:строени|состав)/u.test(prefix);
      if (absIdx >= 0 && !((startsWithStrong || structurePrefix) && DETECTOR_NAMED_IDS.has(strong.id))) return "abstract";
      if (structurePrefix) return "object";
      return "object";
    }
    if (grpIdx >= 0) return absIdx >= 0 && absIdx < grpIdx ? "abstract" : "group";
    return "abstract";
  }

