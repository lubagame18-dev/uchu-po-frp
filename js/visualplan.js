  /* Возвращает {type:"object", term} только для ЧИСТО предметной темы:
     ни одного стоп-маркера в тексте, голова — конкретное существительное.
     Иначе — null (план остаётся символическим, 0 выдумок). */
  function detectTermObject(rawText) {
    const raw = String(rawText == null ? "" : rawText);
    const rawWords = raw.replace(/[«»"()]/g, " ").split(/\s+/).filter(Boolean);
    for (let i = 1; i < rawWords.length; i++) {
      if (/^[А-ЯЁ]/.test(rawWords[i])) return null; /* имя/топоним — не предмет */
    }
    const t = norm(raw).replace(/[«»"()]/g, " ").replace(/\b\d+\b/g, " ").replace(/\s+/g, " ").trim();
    const words = t.split(" ").filter(w => w.length >= 3);
    if (!words.length) return null;
    const keep = words.filter(w => !termHasStem(w, TERM_STOP_STEMS) && !TERM_ADJ_RE.test(w));
    if (keep.length !== 1) return null;
    const head = keep[0];
    if (!/^[а-яё][а-яё-]*$/.test(head) || head.length < 4) return null;
    if (termHasStem(head, TERM_GROUP_STEMS) || /(?:ые|ие)$/.test(head)) return null;
    if (TERM_ABS_RE.test(head)) return null;
    const headIdx = words.lastIndexOf(head);
    for (let i = 0; i < words.length; i++) {
      if (i === headIdx) continue;
      if (termHasStem(words[i], TERM_STOP_STEMS)) return null;
    }
    return { type: "object", term: head };
  }

