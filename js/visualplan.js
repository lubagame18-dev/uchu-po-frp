  function ruTitleFromName(name) {
    const n = String(name || "").trim();
    if (!n) return "";
    if (n.indexOf(",") >= 0) return n;
    const words = n.split(/\s+/).filter(Boolean);
    // «Иван III Васильевич», «Пётр I» — в базе сайта это уже статья-название.
    if (words.some(w => /^[IVX]+$/.test(w))) return n;
    if (words.length >= 3) {
      const last = words[words.length - 1];
      return last + ", " + words.slice(0, -1).join(" ");
    }
    return n;
  }

  function surnameCandidates(name, forms) {
    const out = [];
    const push = w => {
      const n = normName(w).replace(/ /g, "");
      if (n && !out.includes(n)) out.push(n);
    };
    const src = [String(name || "")].concat(Array.isArray(forms) ? forms : []);
    for (const raw of src) {
      const s = String(raw || "").trim();
      if (!s) continue;
      if (s.indexOf(",") >= 0) { push(s.split(",")[0]); continue; }
      const words = s.split(/\s+/).filter(w =>
        w && !/^[IVX]+$/.test(w) &&
        !EPITHET_STOP.has(norm(w)) &&
        w.replace(/[^A-Za-zА-Яа-яЁё]/g, "").length > 1
      );
      if (words.length) push(words[words.length - 1]);
    }
    return out;
  }

