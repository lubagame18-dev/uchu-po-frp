  function templateFor(input) {
    const src = isObj(input) ? input : {};
    const slide = isObj(src.slide) ? src.slide : {};
    const subject = subjectCode(src.subject);
    const topic = cleanText(src.topic || src.title || slide.title || "");
    const title = cleanText(slide.title || src.title || "");
    const body = typeof slide.body === "string" ? slide.body : "";
    const kind = schemeKind({ subject, topic, title, body });
    if (!kind) return null;
    if (mapRequestInText([topic, title].join(" "))) return null;
    const fn = svgTemplates[kind.template];
    if (typeof fn !== "function") return null;
    return fn({ kind: kind.kind });
  }

