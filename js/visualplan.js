  function isSymbolic(plan) {
    const meta = planMeta(plan);
    if (meta && typeof meta.symbolic === "boolean") return meta.symbolic;
    const prompt = isObj(plan) && typeof plan.image_prompt === "string" ? plan.image_prompt : "";
    return SYMBOLIC_PROMPT_RE.test(prompt);
  }

  function grounding(plan) {
    const meta = planMeta(plan);
    if (!meta || !hasOwn(meta, "topicType")) {
      return {
        grounded: false, objectKey: null, sourceWords: [], symbolic: isSymbolic(plan),
        topicType: "abstract", intent: "", slideLevel: false, allowed: false, reason: "", groundSource: ""
      };
    }
    return {
      grounded: meta.grounded === true,
      objectKey: meta.objectKey || null,
      sourceWords: Array.isArray(meta.sourceWords) ? meta.sourceWords.slice() : [],
      symbolic: meta.symbolic === true,
      topicType: meta.topicType || "abstract",
      intent: typeof meta.intent === "string" ? meta.intent : "",
      slideLevel: meta.slideLevel === true,
      allowed: meta.allowed === true,
      reason: typeof meta.reason === "string" ? meta.reason : "",
      groundSource: typeof meta.groundSource === "string" ? meta.groundSource : ""
    };
  }

