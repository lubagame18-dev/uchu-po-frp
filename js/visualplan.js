  function personInText(text) {
    const raw = String(text == null ? "" : text);
    if (!raw) return null;
    const tokens = tokensOf(raw).filter(isCapitalized);
    if (!tokens.length) return null;
    const idx = buildPersonIndex();
    const found = new Map();
    for (const token of tokens) {
      const n = normName(token).replace(/\s/g, "");
      if (!n || n.length < 3) continue;
      if (PLURAL_ADJECTIVE_STOP.has(n)) continue;
      if (GENERIC_WORD_STOP.has(n)) continue;
      const plain = n.replace(/-/g, "");
      const stemKey = stemOf(plain);
      if (!stemKey) continue;
      const bucketKeys = [stemKey, stemKey.slice(0, 3)];
      if (n.indexOf("-") >= 0) {
        const firstPart = n.split("-")[0];
        bucketKeys.push(firstPart, stemOf(firstPart), stemOf(firstPart).slice(0, 3));
      }
      for (const key of bucketKeys) {
        const list = idx.bySurname.get(key);
        if (!list) continue;
        for (const person of list) {
          for (const surname of person.surnames) {
            if (!tokenMatchesSurname(n, surname)) continue;
            // Голое имя («Пётр», «Иван») не должно цепляться за чужую фамилию («Петров»).
            const tn = norm(n);
            const sn = normName(surname).replace(/\s/g, "");
            if (isCommonFirstName(tn) && tn !== sn.replace(/-/g, "") && tn.length <= sn.replace(/-/g, "").length) continue;
            // «Пётр I», «Людовик XIV»: голое имя без номера — ещё не та персона.
            if (person.roman && isCommonFirstName(surname) && !hasRomanPhrase(raw, surname, person.roman)) continue;
            let score = 3;
            const fw = firstWordOf(person.name);
            if (fw && tokens.some(t => t !== token && tokenMatchesSurname(normName(t), fw))) score += 2;
            const prev = found.get(person);
            if (!prev || prev.score < score) found.set(person, { person, score });
            break;
          }
        }
      }
    }
    let best = null;
    for (const item of found.values()) if (!best || item.score > best.score) best = item;
    return best ? best.person : null;
  }

