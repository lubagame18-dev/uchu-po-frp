  async function attemptAdapter(name, fn, arg) {
    if (typeof fn !== "function") return null;
    try {
      const value = await fn(arg);
      if (typeof value === "string" && value.trim()) return { url: value.trim(), source: name };
      return null;
    } catch (e) {
      return null;
    }
  }

  async function acquire(plan, adapters) {
    const p = isObj(plan) ? plan : {};
    const A = isObj(adapters) ? adapters : {};
    const meta = p.__vp_meta || {};
    const seed = deriveSeedFromPlan(p);
    const strategy = p.editorial_check && p.editorial_check.visual_strategy;
    const prompt = typeof p.image_prompt === "string" ? p.image_prompt : "";
    const es = isObj(p.extra_sources) ? p.extra_sources : {};
    const tags = Array.isArray(es.library_tags) ? es.library_tags.join(" ") : "";
    const person = planPerson(p);

    if (strategy === "site_library") {
      let hit = await attemptAdapter("library", A.library, tags);
      if (hit) return hit;
      if (person) {
        const title = person.ruTitle || person.name || p.title || "";
        hit = await attemptAdapter("wikiRu", A.wikiRu, title);
        if (hit) return hit;
      }
      hit = await attemptAdapter("flux", A.flux, prompt);
      if (hit) return hit;
    } else if (strategy === "ru_wikipedia_api") {
      const title = es.ru_wiki_title || "";
      let hit = await attemptAdapter("wikiRu", A.wikiRu, title);
      if (hit) return hit;
      hit = await attemptAdapter("flux", A.flux, prompt);
      if (hit) return hit;
    } else if (strategy === "en_wikimedia_api") {
      const query = es.en_wiki_query || "";
      let hit = await attemptAdapter("wikiEn", A.wikiEn, query);
      if (hit) return hit;
      const portraitLike = (meta.intent === "person" || meta.intent === "masterpiece") || (!meta.intent && person && PORTRAIT_INTENT.test([p.title, (p.facts || []).join(" ")].join(" ")));
      if (!portraitLike) {
        hit = await attemptAdapter("flux", A.flux, prompt);
        if (hit) return hit;
      }
    } else if (strategy === "svg_code") {
      const markup = typeof es.svg_markup === "string" ? es.svg_markup : "";
      let hit = null;
      if (markup && typeof A.svg === "function") hit = await attemptAdapter("svg", A.svg, markup);
      else if (markup) hit = { url: svgDataUrl(markup), source: "svg" };
      if (hit) return hit;
    } else {
      let hit = await attemptAdapter("flux", A.flux, prompt);
      if (hit) return hit;
    }

    let fallback = await attemptAdapter("fallback", A.fallback, seed);
    if (fallback) return fallback;
    const subject = meta.subject || (typeof p.__vp_meta === "object" && p.__vp_meta ? p.__vp_meta.subject : "");
    return { url: svgDataUrl(fallbackSvg(seed, subject)), source: "fallback" };
  }

