      if (ruTitle) add("EXTRA_SOURCE_STRAY", p + "extra_sources.ru_wiki_title", "лишнее поле для svg_code");
      if (enQuery) add("EXTRA_SOURCE_STRAY", p + "extra_sources.en_wiki_query", "лишнее поле для svg_code");
