  function passportClaims(passport) {
    const text = String(passport || "");
    const out = [];
    const eraRe = /(?:эпоха|Эпоха)\s*:\s*([^;.]{2,60})/g;
    const regionRe = /(?:регион|Регион)\s*:\s*([^;.]{2,60})/g;
    let m;
    while ((m = eraRe.exec(text)) !== null) out.push({ kind: "era", value: m[1].trim() });
    while ((m = regionRe.exec(text)) !== null) out.push({ kind: "region", value: m[1].trim() });
    return out;
  }

  function eraClaimUnsupported(claimValue, sourceText) {
    const c = norm(claimValue);
    const src = norm(sourceText);
    if (!c) return false;
    if (/древн/.test(c)) return !/(?:^| )(?:древн|древност)/u.test(src);
    if (/античн/.test(c)) return !/(?:^| )(?:античн|античност|грец|римск)/u.test(src);
    if (/средневек|средние века|средних веков/.test(c)) return !/(?:^| )средневеков/u.test(src);
    if (/возрожден|ренессанс/.test(c)) return !/(?:^| )(?:возрожден|ренессанс)/u.test(src);
    if (/первобытн/.test(c)) return !/(?:^| )(?:первобытн|неолит|палеолит|мезолит)/u.test(src);
    if (/советск/.test(c)) return !/(?:^| )(?:советск|ссср)/u.test(src);
    if (/петровск/.test(c)) return !/(?:^| )петровск/u.test(src);
    if (/просвещ/.test(c)) return !/(?:^| )просвещ/u.test(src);
    const roman = c.match(/(?:^| )(xxi|xx|xix|xviii|xvii|xvi|xv|xiv)(?= |$)/);
    if (roman) {
      const num = ROMAN_TO_NUM[roman[1]];
      const numRe = new RegExp("(?:^| )" + num + "(?= |$)", "u");
      const romanRe = new RegExp("(?:^| )" + roman[1] + "(?= |$)", "u");
      const wordRe = CENTURY_WORDS[num] || null;
      return !(numRe.test(src) || romanRe.test(src) || (wordRe && wordRe.test(src)));
    }
    const wordCentury = c.match(/(?:^| )(четырнадцат|пятнадцат|шестнадцат|семнадцат|восемнадцат|девятнадцат|двадцат)/);
    if (wordCentury) return !new RegExp("(?:^| )" + wordCentury[1]).test(src);
    return false;
  }

  function regionClaimUnsupported(claimValue, sourceText) {
    const c = String(claimValue || "");
    const src = norm(sourceText);
    for (const cue of REGION_CLAIM_CUES) {
      if (!cue.claim.test(c)) continue;
      return !cue.src.test(src);
    }
    return false;
  }

  /* Внешний JSON (без меты): предмет в промпте без опоры в заголовке/фактах. */
  function externalUngroundedObject(promptText, sourceText) {
    if (!OBJECT_EN_RE.test(promptText)) return "";
    const src = norm(sourceText);
    for (const entry of GROUNDED_OBJECTS) {
      entry.re.lastIndex = 0;
      if (entry.re.test(src)) continue;
      const head = entry.en.split(" ").slice(0, 3).join(" ");
      if (!head) continue;
      const re = new RegExp(head.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "i");
      if (re.test(promptText)) return entry.id;
    }
    return "";
  }

  function checkGroundedPlan(slide, path, add, promptText, anchorText, title, facts) {
    const p = path ? path + "." : "";
    const meta = planMeta(slide);
    if (GENERIC_ANCHOR_RE.test(anchorText)) {
      add("GENERIC_ANCHOR", p + "editorial_check.visual_anchor", "обобщённый anchor-бойлерплейт: " + anchorText.slice(0, 80));
    }
    if (typeof promptText === "string" && FAKE_OBJECT_RE.test(promptText)) {
      add("FAKE_OBJECT", p + "image_prompt", "в промпте старый шаблонный объект, которого нет в теме");
    }
    const passport = isObj(slide.editorial_check) && typeof slide.editorial_check.historical_or_scientific_passport === "string"
      ? slide.editorial_check.historical_or_scientific_passport
      : "";
    const claims = passportClaims(passport);
    const sourceText = [title].concat(Array.isArray(facts) ? facts : []).join(" ");
    const strategy = isObj(slide.editorial_check) ? String(slide.editorial_check.visual_strategy || "") : "";
    if (meta) {
      if (meta.symbolic === true && typeof promptText === "string" && OBJECT_EN_RE.test(promptText)) {
        add("SYMBOLIC_WITH_OBJECT", p + "image_prompt", "символический план содержит конкретный предмет");
      }
      if (meta.grounded === true && (!Array.isArray(meta.sourceWords) || !meta.sourceWords.length)) {
        add("UNGROUNDED_OBJECT", p + "image_prompt", "предмет в плане без опоры в теме/фактах");
      }
      for (const claim of claims) {
        if (claim.kind === "era" && !meta.eraSource) {
          add("UNSUPPORTED_ERA", p + "editorial_check.historical_or_scientific_passport", "эпоха в паспорте не следует из источника: " + claim.value);
        }
        if (claim.kind === "region" && !meta.regionSource) {
          add("UNSUPPORTED_ERA", p + "editorial_check.historical_or_scientific_passport", "регион в паспорте не следует из источника: " + claim.value);
        }
      }
    } else {
      if (strategy === "flux_generation" && !SYMBOLIC_PROMPT_RE.test(promptText)) {
        if (externalUngroundedObject(promptText, sourceText)) {
          add("UNGROUNDED_OBJECT", p + "image_prompt", "конкретный предмет в промпте без опоры в заголовке/фактах слайда");
        }
      }
      for (const claim of claims) {
        if (claim.kind === "era" && eraClaimUnsupported(claim.value, sourceText)) {
          add("UNSUPPORTED_ERA", p + "editorial_check.historical_or_scientific_passport", "эпоха в паспорте не следует из источника: " + claim.value);
        }
        if (claim.kind === "region" && regionClaimUnsupported(claim.value, sourceText)) {
          add("UNSUPPORTED_ERA", p + "editorial_check.historical_or_scientific_passport", "регион в паспорте не следует из источника: " + claim.value);
        }
      }
    }
  }

  function validate(x) {
    const errors = [];
    const add = (code, path, message) => errors.push({ code, path, message });
    if (x === null || x === undefined || typeof x !== "object") {
      add("EMPTY_SLIDE", "slide", "план не является объектом");
      return { ok: false, errors };
    }
    if (Array.isArray(x.slides)) {
      if (!x.slides.length) add("EMPTY_SLIDE", "slides", "в презентации нет слайдов");
      x.slides.forEach((slide, i) => {
        if (!isObj(slide)) add("EMPTY_SLIDE", "slides[" + i + "]", "слайд не является объектом");
        else checkSlidePlan(slide, "slides[" + i + "]", add);
      });
      return { ok: errors.length === 0, errors };
    }
    checkSlidePlan(x, "slide", add);
    return { ok: errors.length === 0, errors };
  }

