  /* Промпт: 60–120 слов, английский, без цифр/имён, ровно с NEG_TAIL. */
  function finalizePrompt(body) {
    let text = String(body == null ? "" : body).replace(/\s+/g, " ").trim().replace(/[,\s]+$/, "");
    if (!/[.!?]$/.test(text)) text += ".";
    if (wordCount(text) + wordCount(NEG_TAIL) < MIN_PROMPT_WORDS) {
      text = text.replace(/[.]$/, "") + ", in a calm uncluttered educational space with a plain neutral background.";
    }
    const maxBody = MAX_PROMPT_WORDS - wordCount(NEG_TAIL);
    const words = text.split(/\s+/).filter(Boolean);
    if (words.length > maxBody) {
      text = words.slice(0, maxBody).join(" ").replace(/[,\s]+$/, "") + ".";
    }
    let prompt = text + " " + NEG_TAIL;
    if (prompt.length > 900) {
      const tail = " " + NEG_TAIL;
      let trimmed = text;
      while (trimmed.length + tail.length > 900 && trimmed.length > 120) {
        const cut = trimmed.lastIndexOf(" ");
        trimmed = cut > 80 ? trimmed.slice(0, cut) : trimmed.slice(0, 120);
      }
      trimmed = trimmed.replace(/[,\s]+$/, "");
      if (!/[.!?]$/.test(trimmed)) trimmed += ".";
      prompt = trimmed + tail;
    }
    return prompt;
  }

