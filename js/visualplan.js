  function libraryTagsRelevant(topicTitle, tags) {
    const t = norm(topicTitle);
    if (!t) return false;
    const words = t.split(" ").filter(w => w.length >= 4);
    if (!words.length) return false;
    for (const tag of tags || []) {
      for (const w of norm(tag).split(" ")) {
        if (w.length < 4) continue;
        if (words.some(x => x === w || x.startsWith(w) || (w.startsWith(x) && w.length - x.length <= 3))) return true;
      }
    }
    return false;
  }

  function libraryTagsFor(text, subject) {
    const src = String(text || "");
    const code = subjectCode(subject);
    for (const rule of LIBRARY_RULES) {
      if (rule.subjects && rule.subjects.indexOf(code) < 0) continue;
      if (!rule.re.test(src)) continue;
      const tags = rule.tags(src).filter(Boolean).map(String);
      const uniq = [];
      for (const t of tags) if (t && !uniq.includes(t)) uniq.push(t.trim());
      if (uniq.length >= 2 && libraryTagsRelevant(src, uniq)) return uniq.slice(0, 4);
    }
    return null;
  }

