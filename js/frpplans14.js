/* Доработка содержательной базы: заполняем разделы, которые были без уроков.
   Информатика 7 — алгоритмы; информатика 8 — цифровая грамотность и информационные технологии;
   биология 8 — систематика животных.
   Модуль регистрируется в FRP_EXTRAS и применяется повторно, поэтому порядок загрузки не важен.
   Формулировки тем, содержания и видов деятельности — собственные. */
window.FRPPlans = window.FRPPlans || {};
(function () {
  const P = window.FRPPlans;

  /* добавить уроки в существующий раздел; при необходимости — новую тему ФРП */
  function addLessons(subject, grade, sectionName, themeRow, lessons) {
    const plan = P[subject] && P[subject][grade];
    if (!plan || !plan.s || !plan.l) return;
    const si = plan.s.indexOf(sectionName);
    if (si < 0) return;
    if (lessons.every(t => plan.l.some(r => r[0].toLowerCase() === t.toLowerCase()))) return;

    let ti = -1;
    if (themeRow) {
      const key = String(themeRow[0]).toLowerCase();
      ti = plan.th.findIndex(r => String(r[0]).toLowerCase() === key);
      if (ti < 0) { plan.th.push(themeRow); ti = plan.th.length - 1; }
    } else {
      ti = plan.th.findIndex(r => String(r[0]).toLowerCase().includes(sectionName.toLowerCase()));
    }

    lessons.forEach(title => {
      if (plan.l.some(r => r[0].toLowerCase() === title.toLowerCase())) return;
      plan.l.push([title, si, ti >= 0 ? ti : -1]);
    });
  }

  function apply() {
    /* ---------- Информатика, 7 класс: алгоритмы и программирование ---------- */
    addLessons("inf", "7", "Алгоритмы и программирование",
      ["Алгоритмы и программирование",
        "Понятие алгоритма, его свойства (дискретность, детерминированность, конечность, массовость, результативность). Исполнитель алгоритма и его система команд. Способы записи алгоритмов: словесный, табличный, в виде блок-схемы. Базовые алгоритмические конструкции: следование, ветвление, цикл. Разработка алгоритмов для формальных исполнителей.",
        "Понимать смысл понятия «алгоритм» и приводить примеры из жизни; описывать исполнителя и его команды; записывать алгоритм словесно и в виде блок-схемы; составлять алгоритмы со следованием, ветвлением и циклом."],
      ["Понятие алгоритма и его свойства", "Исполнитель алгоритма и система команд",
        "Способы записи алгоритмов", "Алгоритмы со следованием и ветвлением", "Алгоритмы с циклами"]);

    /* ---------- Информатика, 8 класс: цифровая грамотность ---------- */
    addLessons("inf", "8", "Цифровая грамотность",
      ["Цифровая грамотность",
        "Файлы и папки, размер файла, архивация. Компьютерные сети: объединение компьютеров, интернет, адресация, поиск информации. Основы безопасной работы: пароли, защита данных, вредоносные программы, сетевой этикет.",
        "Оперировать файлами и размерами данных; объяснять устройство сети и адресацию; искать информацию по ключевым словам; соблюдать правила безопасности в сети."],
      ["Файлы, папки и размеры данных", "Компьютерные сети и интернет",
        "Поиск информации и оценка источников", "Безопасность при работе в сети"]);

    /* ---------- Информатика, 8 класс: информационные технологии ---------- */
    addLessons("inf", "8", "Информационные технологии",
      ["Информационные технологии",
        "Электронные (динамические) таблицы: структура таблицы, ячейка и адрес, формулы и функции, вычисления, копирование формул, сортировка и фильтрация данных, построение диаграмм.",
        "Создавать таблицу и заполнять данные; записывать формулы и использовать функции; копировать формулы с учётом ссылок; сортировать и фильтровать данные; строить диаграммы."],
      ["Электронная таблица: структура и данные", "Формулы и ссылки на ячейки",
        "Функции и вычисления в таблицах", "Сортировка, фильтрация и диаграммы"]);

    /* ---------- Биология, 8 класс: систематика животных ---------- */
    addLessons("bio", "8", "Основные категории систематики животных", null,
      ["Вид как основная единица систематики", "Бинарная номенклатура",
        "Систематические категории животных и их соподчинение", "Классификация животных: практикум"]);

    /* ---------- География 10–11: «Резервное время» ссылалось на несуществующий раздел ---------- */
    ["10", "11"].forEach(g => {
      const plan = P.geo && P.geo[g];
      if (!plan || !plan.s) return;
      const need = plan.l.some(r => /^Резервное время/.test(String(r[0])) && (r[1] < 0 || r[1] >= plan.s.length));
      if (!need) return;
      if (!plan.s.includes("Резервное время")) plan.s.push("Резервное время");
      const si = plan.s.length - 1;
      plan.l.forEach(r => {
        if (/^Резервное время/.test(String(r[0])) && (r[1] < 0 || r[1] >= plan.s.length - 1)) r[1] = si;
      });
    });
  }

  window.FRP_EXTRAS = window.FRP_EXTRAS || [];
  window.FRP_EXTRAS.push(apply);
  apply();
})();
