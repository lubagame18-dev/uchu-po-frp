/* «Учу по ФРП» — окружающий мир 1–4 классов без нейросети.
   Локальная сборка урока: наблюдения, опыты, сравнения, правила безопасности,
   задания с ответами и рабочий лист. */
window.OkrPrimary = (() => {
  "use strict";
  const cap = s => String(s || "").replace(/^./, c => c.toUpperCase());
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const rnd = seed => { let h = 2166136261; for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 100000) / 100000; }; };
  const pick = (r, a) => a[Math.floor(r() * a.length)];

  const B = {
    seasons: ["зима", "весна", "лето", "осень"],
    months: ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"],
    animals: ["заяц", "лиса", "волк", "медведь", "белка", "ёж", "птица", "рыба"],
    plants: ["берёза", "дуб", "сосна", "ромашка", "одуванчик", "клён", "крапива"],
    rules: ["переходить дорогу по пешеходному переходу на зелёный сигнал", "не играть со спичками", "не купаться без взрослых", "мыть руки перед едой", "не открывать дверь незнакомым", "соблюдать режим дня"],
    water: ["вода не имеет формы, принимает форму сосуда", "вода растворяет некоторые вещества", "вода при нагревании расширяется", "вода может быть твёрдой, жидкой, газообразной"],
    air: ["воздух прозрачен и не имеет запаха", "воздух занимает место", "воздух при нагревании расширяется"],
    magnet: ["магнит притягивает металлические предметы", "магнит не притягивает дерево, бумагу, стекло"],
    body: ["глаза — орган зрения", "уши — орган слуха", "нос — орган обоняния", "кожа — орган осязания", "язык — орган вкуса"]
  };

  function kindOf(topic) {
    const t = norm(topic);
    if (/безопасн|дорог|пожар|правил|осторож/.test(t)) return "safety";
    if (/времен|сезон|погод|природ/.test(t)) return "nature";
    if (/животн|звер|птиц|рыб|насеком/.test(t)) return "animals";
    if (/растен|дерев|цвет|лист/.test(t)) return "plants";
    if (/человек|тело|орган|здоров|гигиен|режим/.test(t)) return "body";
    if (/вод|воздух|опыт|веществ|свойств/.test(t)) return "experiment";
    if (/родн|край|город|семь|професс|символ/.test(t)) return "homeland";
    return "nature";
  }

  function explain(kind) {
    const m = {
      safety: ["Безопасность — это правила, которые защищают жизнь и здоровье.", "Дорогу переходим по переходу и на зелёный сигнал.", "Дома нельзя играть со спичками и трогать электроприборы мокрыми руками.", "Опасные ситуации обсуждаем и заранее решаем, как действовать."],
      nature: ["Природа бывает живая и неживая.", "Живая природа: растения, животные, человек; неживая: вода, воздух, камни.", "Времена года сменяются по порядку, у каждого свои признаки.", "Наблюдение — это изучение природы глазами и приборами."],
      animals: ["Животные питаются, дышат, двигаются, растут и размножаются.", "Звери, птицы, рыбы, насекомые различаются по строению и среде.", "Пищевые цепи показывают, кто кем питается.", "Приспособления помогают животным выжить."],
      plants: ["Растения растут, дышат, питаются, размножаются.", "Части растения: корень, стебель, лист, цветок, плод.", "Деревья, кустарники, травы различаются по строению.", "Листья, цветы, плоды различаются по форме и размеру."],
      body: ["Органы чувств помогают познавать мир.", "Тело нужно беречь: гигиена, режим дня, движение, отдых.", "Правильное питание и сон важны для здоровья.", "Признаки болезни — повод сообщить взрослым."],
      experiment: ["Опыт проверяет предположение.", "Сначала цель, затем оборудование, ход и вывод.", "Наблюдаем и записываем, что изменилось.", "Свойства воды и воздуха можно проверить опытным путём."],
      homeland: ["Родной край — место, где мы живём.", "Символы страны: флаг, герб, гимн.", "Профессии важны для жизни людей.", "Семья — близкие люди, которые заботятся друг о друге."]
    };
    return m[kind] || m.nature;
  }

  function tasks(kind, grade, seed) {
    const r = rnd(seed), out = [];
    const add = (q, a) => out.push({ q, a });
    if (kind === "safety") {
      add("Где можно переходить дорогу?", "по пешеходному переходу и только на зелёный сигнал");
      add("Что делать, если в доме начался пожар?", "сообщить взрослым, вызвать 101/112, выйти на улицу");
      add("Можно ли открывать дверь незнакомым?", "нет, звать взрослых");
      add("Правило перед едой?", "мыть руки");
    } else if (kind === "nature") {
      add("Перечисли времена года по порядку.", "зима, весна, лето, осень");
      add("Чем живая природа отличается от неживой?", "живая дышит, питается, растёт, размножается");
      add("Какие признаки весны?", "тепло, тает снег, прилетают птицы, появляются листья");
      add("Что относится к неживой природе?", "вода, воздух, камни, солнце");
    } else if (kind === "animals") {
      add("Назови признаки животных.", "дышат, питаются, двигаются, растут, размножаются");
      add("Кто из них зверь: заяц, воробей или щука?", "заяц");
      add("Составь пищевую цепь: трава — заяц — ?", "лиса");
      add("Зачем животным приспособления?", "чтобы выжить в своей среде");
    } else if (kind === "plants") {
      add("Назови части растения.", "корень, стебель, лист, цветок, плод");
      add("Чем дерево отличается от кустарника?", "у дерева один ствол, у кустарника несколько");
      add("Что нужно растению для роста?", "свет, вода, воздух, тепло");
      add("Назови дерево нашего края.", "берёза, дуб, сосна");
    } else if (kind === "body") {
      add("Какой орган отвечает за зрение?", "глаза");
      add("Что помогает сохранить здоровье?", "режим дня, гигиена, движение, сон, питание");
      add("Сколько раз в день чистят зубы?", "2 раза — утром и вечером");
      add("Почему важно гулять на улице?", "организм получает кислород и закаляется");
    } else if (kind === "experiment") {
      const w = pick(r, B.water), a = pick(r, B.air);
      add(`Опыт: как проверить свойство воды? (${w})`, "описать, что наблюдали, и сделать вывод");
      add(`Опыт: воздух — что можно сказать? (${a})`, "прозрачный, без запаха, занимает место");
      add("Что произойдёт с водой в морозилке?", "замёрзнет, превратится в лёд");
      add("Что произойдёт с сахаром в воде?", "растворится");
    } else {
      add("Назови символы нашей страны.", "флаг, герб, гимн");
      add("Кто заботится о тебе в семье?", "родители, бабушки, дедушки");
      add("Назови профессии людей в школе.", "учитель, библиотекарь, повар, врач");
      add("Чем знаменит твой край?", "ответ по наблюдениям и рассказам");
    }
    return out;
  }

  function conspect(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + g);
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, проверка готовности."],
      ["2", "Актуализация", "4–5", `Вспоминаем: ${explain(kind)[0]} Отвечаем на вопросы по теме «${p.topic}».`],
      ["3", "Наблюдение / опыт", "8–10", `Рассматриваем картинки и объекты, проводим наблюдение. ${explain(kind)[2]} Записываем результат в таблицу.`],
      ["4", "Новое знание", "8–10", explain(kind).join(" ") + " Работаем со схемой и учебником, проговариваем вывод."],
      ["5", "Физминутка", "2", "Имитируем движения животных, смена деятельности."],
      ["6", "Закрепление в игре", "7–8", `Игра «Верно — неверно» и задания: ${ts.slice(0, 3).map(x => x.q).join("; ")}.`],
      ["7", "Самостоятельная работа", "5–6", `Карточки: ${ts.slice(3).map(x => x.q).join("; ")}. Самопроверка.`],
      ["8", "Итог и рефлексия", "2–3", "Что узнали? Что было интересно? Что нужно запомнить?"],
      ["9", "Домашнее задание", "1–2", "Наблюдение за природой/рисунок по теме, выучить правила."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const taskTable = "| № | Задание | Ответ |\n|---|---|---|\n" + ts.map((x, i) => `| ${i + 1} | ${x.q} | ${x.a} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Окружающий мир · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Формировать представления по теме «${p.topic}»: наблюдать, сравнивать, объяснять и применять правила безопасного и бережного поведения.`,
      "",
      "## Планируемые результаты",
      "**Предметные:** называть объекты и признаки, сравнивать, объяснять связи, знать правила.",
      "**Метапредметные:** наблюдать, сравнивать, делать вывод, работать с карточкой.",
      "**Личностные:** бережное отношение к природе, забота о здоровье, безопасное поведение.",
      "",
      "## Опорные знания",
      explain(kind).map(x => "- " + x).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Задания с ответами",
      taskTable,
      "",
      "## Правила безопасности",
      "Дорога: по переходу и на зелёный сигнал. Дом: без взрослых — никаких спичек и электроприборов. Вода: купаться только со взрослыми.",
      "",
      "## Оценивание",
      "Наблюдение, ответы, аккуратность, умение объяснить; ошибки разбираем вместе.",
      "",
      "## Домашнее задание",
      `Наблюдение по теме «${p.topic}» (записать/нарисовать), повторить правила.`
    ].join("\n");
  }

  function worksheet(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + "ws");
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. Рассмотри и подпиши",
      explain(kind)[0],
      "",
      "## 2. Проверь знания",
      ts.slice(0, 4).map((x, i) => `${i + 1}) ${x.q}`).join("\n"),
      "",
      "## 3. Опыт / наблюдение",
      "Запиши, что наблюдал и какой сделал вывод.",
      "",
      "## 4. Правила",
      "Нарисуй знак безопасного поведения по теме.",
      "",
      "## 5. Рефлексия",
      "Что узнал нового? Что было трудным?"
    ].join("\n");
  }

  return { kindOf, tasks, explain, conspect, worksheet, lesson: conspect };
})();
