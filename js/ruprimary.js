/* «Учу по ФРП» — русский язык 1–4 классов без нейросети.
   Локальная сборка конспекта и рабочего листа по теме урока: звуки и буквы,
   орфограммы, состав слова, части речи, предложение и текст, словарные слова. */
window.RuPrimary = (() => {
  "use strict";
  const cap = s => String(s || "").replace(/^./, c => c.toUpperCase());
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const rnd = seed => { let h = 2166136261; for (const c of String(seed)) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return () => { h ^= h << 13; h ^= h >>> 17; h ^= h << 5; return ((h >>> 0) % 100000) / 100000; }; };
  const pickN = (r, a, n) => { const b = [...a]; const out = []; while (out.length < n && b.length) out.push(b.splice(Math.floor(r() * b.length), 1)[0]); return out; };

  const BANKS = {
    zhi: ["лужи", "машина", "шишка", "камыши", "ежи", "мыши", "лыжи", "кувшин"],
    cha: ["чаща", "роща", "свеча", "пища", "щавель", "чайка", "туча", "дача"],
    chu: ["чудо", "щука", "чулок", "щупальца", "чугун", "ищу", "тащу", "чищу"],
    bezud: [["вода", "воды"], ["трава", "травы"], ["леса", "лес"], ["зима", "зимы"], ["стена", "стены"], ["окно", "окна"], ["столы", "стол"], ["мосты", "мост"]],
    parnye: [["дуб", "дубы"], ["зуб", "зубы"], ["глаз", "глаза"], ["снег", "снега"], ["хлеб", "хлеба"], ["друг", "друга"]],
    slov1: ["класс", "ученик", "тетрадь", "пенал", "карандаш", "учитель"],
    slov2: ["город", "деревня", "корова", "молоко", "воробей", "собака"],
    slov3: ["картина", "комната", "лестница", "растение", "урожай", "здоровье"],
    slov4: ["библиотека", "путешествие", "правительство", "интересный", "аккуратно"],
    parts: [["переход", "приставка, корень"], ["лесной", "корень, суффикс, окончание"], ["тропинка", "корень, суффикс, окончание"], ["домик", "корень, суффикс"], ["книжка", "корень, суффикс, окончание"], ["заморозки", "приставка, корень, суффикс, окончание"]],
    nouns: ["стол", "кот", "книга", "окно", "школа"],
    adjs: ["красный", "добрый", "зимний", "весёлый", "маленький"],
    verbs: ["бежит", "читает", "рисует", "поёт", "играет"]
  };

  function kindOf(topic) {
    const t = norm(topic);
    if (/жи-?ши|ча-?ща|чу-?щу/.test(t)) return "orfogramma";
    if (/безударн|парн|орфограмм|проверочн|корн/.test(t)) return "orfogramma";
    if (/звук|букв|слог|ударени|грамот|алфавит/.test(t)) return "gramota";
    if (/состав|приставк|суффикс|окончани|разбор слов/.test(t)) return "parts";
    if (/част[ьи] речи|существительн|прилагательн|глагол/.test(t)) return "speech";
    if (/предложени|текст|изложени|сочинени|речь/.test(t)) return "text";
    if (/словарн/.test(t)) return "slovar";
    return "gramota";
  }

  function orfoRows(kind, grade) {
    const r = rnd("ru" + grade + kind);
    const rows = [];
    if (/жи|ши|ча|ща|чу|щу/i.test(kind)) rows.push(["Вставь пропущенную букву", pickN(r, BANKS.zhi, 3).map(w => w.replace(/[жш]/i, m => m + "…")).join(", "), "жи-ши пишем с и"]);
    rows.push(["Вставь пропущенную букву", pickN(r, BANKS.cha.concat(BANKS.chu), 3).map(w => w.replace(/[чщ]/i, m => m + "…")).join(", "), "ча-ща с а, чу-щу с у"]);
    return rows;
  }

  function tasks(kind, grade, seed) {
    const r = rnd(seed), g = +grade, out = [];
    const add = (q, a) => out.push({ q, a });
    if (kind === "gramota") {
      pickN(r, ["мама", "школа", "книга", "ручка", "лес", "зима"], 4).forEach(w => add(`Слого-звуковой разбор: «${w}»`, `${w.length} сл.`.replace("сл.", "слога(ов)") + `, звуков ${w.length} (уточни гласные/согласные)`));
      add("Сколько букв и звуков в слове «ель»?", "3 буквы, 3 звука");
    } else if (kind === "orfogramma") {
      pickN(r, BANKS.zhi.concat(BANKS.cha, BANKS.chu), 4).forEach(w => add(`Вставь пропущенную букву: ${w.replace(/[жшчщ]/i, m => m + "_")}`, w));
      pickN(r, BANKS.bezud, 3).forEach(([w, chk]) => add(`Проверь безударную гласную: ${w} — подбери проверочное слово`, chk));
      pickN(r, BANKS.parnye, 2).forEach(([w, chk]) => add(`Проверь парную согласную: ${w}`, chk));
    } else if (kind === "parts") {
      pickN(r, BANKS.parts, 4).forEach(([w, a]) => add(`Разбери по составу слово «${w}»`, a));
      add("Подбери однокоренные слова к слову «лес»", "лесной, лесник, лесок, перелесок");
    } else if (kind === "speech") {
      add(`Назови существительные: ${pickN(r, BANKS.nouns, 3).join(", ")}`, "стол, кот, книга (и т.п.) — кто? что?");
      add(`Прилагательные к слову «день»`, "солнечный, тёплый, зимний, весёлый");
      add(`Что делает? Глаголы к слову «ученик»`, "читает, пишет, решает, рисует");
    } else if (kind === "text") {
      add("Составь предложение из слов: «весной, птицы, прилетают»", "Весной прилетают птицы.");
      add("Сколько предложений в тексте? (учитель читает текст)", "по тексту урока");
      add("Придумай продолжение: «Наступила зима…»", "свободный ответ с опорой на тему");
    } else if (kind === "slovar") {
      const words = g <= 1 ? BANKS.slov1 : g === 2 ? BANKS.slov2 : g === 3 ? BANKS.slov3 : BANKS.slov4;
      pickN(r, words, 4).forEach(w => add(`Запиши словарное слово по памяти: «${w}»`, w));
      add("Составь предложение с одним словарным словом", "свободный ответ");
    }
    return out;
  }

  function explain(kind, grade) {
    const blocks = {
      gramota: ["Звуки мы слышим и произносим, буквы — пишем и читаем.", "В слове есть гласные и согласные звуки.", "Ударение помогает правильно произносить слово.", "Делим слово на слоги: сколько гласных — столько слогов."],
      orfogramma: ["Орфограмма — место, где можно ошибиться.", "Правило подсказывает, какую букву писать.", "Безударную гласную проверяем ударением.", "Парную согласную проверяем словом, где после неё гласный."],
      parts: ["Слово состоит из частей: корень, приставка, суффикс, окончание.", "Корень — общая часть родственных слов.", "Приставка стоит перед корнем, суффикс — после корня.", "Окончание изменяет форму слова."],
      speech: ["Имя существительное отвечает на вопросы кто? что?", "Прилагательное — какой? какая? какое?", "Глагол — что делать? что делает?", "Части речи помогают строить предложение."],
      text: ["Предложение выражает законченную мысль.", "В предложении есть главные члены: подлежащее и сказуемое.", "Текст состоит из предложений, связанных по смыслу.", "У текста есть тема и главная мысль."],
      slovar: ["Словарные слова запоминаем целиком.", "Их нельзя проверить — нужно запомнить написание.", "Помогают карточки, ребусы и повторение.", "Составляем предложения со словарными словами."]
    };
    return blocks[kind] || blocks.gramota;
  }

  function conspect(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + g);
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, проверка готовности, настрой."],
      ["2", "Чистописание / разминка", "3–4", "Прописываем буквы и соединения по теме; пальчиковая гимнастика."],
      ["3", "Актуализация", "3–4", `Вспоминаем: ${explain(kind, g)[0]} Отвечаем на вопросы по теме «${p.topic}».`],
      ["4", "Новое знание", "8–10", explain(kind, g).slice(0, 3).join(" ") + " Работаем с карточками и доской, проговариваем правило вслух."],
      ["5", "Физминутка", "2", "Упражнения под счёт, смена деятельности."],
      ["6", "Закрепление", "8–10", `Выполняем упражнения: ${ts.slice(0, 3).map(x => x.q).join("; ")}. Проверяем вместе.`],
      ["7", "Самостоятельная работа", "5–7", `По карточкам: ${ts.slice(3).map(x => x.q).join("; ")}. Самопроверка.`],
      ["8", "Итог и рефлексия", "2–3", "Что узнали? Какое правило запомнили? Что было трудно?"],
      ["9", "Домашнее задание", "1–2", "Упражнение по учебнику, повторить правило, словарные слова."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const taskTable = "| № | Задание | Ответ |\n|---|---|---|\n" + ts.map((x, i) => `| ${i + 1} | ${x.q} | ${x.a} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** Русский язык · **Время:** 45 минут`,
      "",
      "## Цель урока",
      `Формировать умение по теме «${p.topic}»: наблюдать, применять правило и проверять написанное.`,
      "",
      "## Планируемые результаты",
      "**Предметные:** различать звуки и буквы, видеть орфограмму, применять правило, проверять написание.",
      "**Метапредметные:** сравнивать, находить закономерность, работать с карточкой, проверять себя.",
      "**Личностные:** интерес к родному языку, аккуратность, внимательность к слову.",
      "",
      "## Опорные знания",
      explain(kind, g).map(x => "- " + x).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Задания с ответами",
      taskTable,
      "",
      "## Словарная работа",
      "Записать 2–3 словарных слова по теме, поставить ударение, подчеркнуть орфограммы.",
      "",
      "## Оценивание",
      "Аккуратность, правильность, умение объяснить правило; ошибки разбираем и исправляем.",
      "",
      "## Домашнее задание",
      `Повторить правило по теме «${p.topic}», выполнить упражнение, запомнить словарные слова.`
    ].join("\n");
  }

  function worksheet(p) {
    const g = +p.grade || 1, kind = kindOf(p.topic), ts = tasks(kind, g, p.topic + "ws");
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${g} · **Имя:** ______________________`,
      "",
      "## 1. Разминка",
      explain(kind, g)[0],
      "",
      "## 2. Вспомни правило",
      explain(kind, g).slice(1, 3).map(x => "- " + x).join("\n"),
      "",
      "## 3. Выполни задания",
      ts.slice(0, 4).map((x, i) => `${i + 1}) ${x.q}`).join("\n"),
      "",
      "## 4. Проверь себя",
      "Сверь с ответами учителя. Отметь: ✓ — верно, ? — было трудно.",
      "",
      "## 5. Придумай сам",
      "Составь одно предложение с изученным правилом.",
      "",
      "## 6. Рефлексия",
      "Что получилось? Что нужно повторить?"
    ].join("\n");
  }

  return { kindOf, tasks, explain, conspect, worksheet, lesson: conspect };
})();
