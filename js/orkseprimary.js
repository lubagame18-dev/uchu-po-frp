/* «Учу по ФРП» — ОРКСЭ без нейросети.
   Модули: основы православной, исламской, буддийской, иудейской культуры,
   основы мировых религиозных культур, основы светской этики.
   Форма — беседа, работа с понятием, разбор ситуации, творческая работа. */
window.OrksePrimary = (() => {
  "use strict";
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const MODULES = {
    prav: { name: "Основы православной культуры", values: ["вера", "добро", "милосердие", "семья", "забота о ближнем"], holidays: ["Рождество", "Пасха"], symbols: ["храм", "икона", "крест"] },
    islam: { name: "Основы исламской культуры", values: ["вера", "милосердие", "справедливость", "семья", "гостеприимство"], holidays: ["Ураза-байрам", "Курбан-байрам"], symbols: ["мечеть", "минарет", "молитвенный коврик"] },
    budd: { name: "Основы буддийской культуры", values: ["сострадание", "спокойствие", "уважение к жизни", "мудрость", "доброта"], holidays: ["Сагаалган — праздник Белого месяца в бурятской традиции", "Весак — праздник в ряде буддийских традиций"], symbols: ["ступа", "мандала", "статуя Будды"] },
    iuda: { name: "Основы иудейской культуры", values: ["вера", "справедливость", "память", "семья", "ответственность"], holidays: ["Песах", "Ханука"], symbols: ["синагога", "звезда Давида", "Тора"] },
    world: { name: "Основы мировых религиозных культур", values: ["уважение", "понимание", "мир между людьми", "доброта", "честность"], holidays: ["Пасха в христианской традиции", "Песах в иудейской традиции"], symbols: ["храм", "мечеть", "синагога", "ступа"] },
    ethics: { name: "Основы светской этики", values: ["добро", "справедливость", "совесть", "долг", "уважение"], holidays: ["день рождения", "семейная годовщина"], symbols: ["договорённость класса", "правило общей игры", "очерёдность дежурства"] }
  };
  function moduleOf(topic) {
    const t = norm(topic);
    if (/православ/.test(t)) return "prav";
    if (/ислам|мусульман/.test(t)) return "islam";
    if (/будд/.test(t)) return "budd";
    if (/иуде|иуда|еврей/.test(t)) return "iuda";
    if (/мир|религи|культур/.test(t)) return "world";
    return "ethics";
  }
  const CORE = [
    ["Что такое добро?", "поступки, которые помогают другим и делают мир лучше"],
    ["Что такое совесть?", "внутреннее чувство, которое подсказывает, что хорошо, а что плохо"],
    ["Что такое долг?", "обязанность, которую человек выполняет по совести"],
    ["Что такое милосердие?", "готовность помочь и проявить сострадание"],
    ["Что такое уважение?", "внимательное и доброе отношение к другому человеку"],
    ["Что такое традиция?", "то, что передаётся из поколения в поколение"],
    ["Что такое семья?", "близкие люди, связанные заботой и поддержкой"],
    ["Что такое культура?", "созданное людьми: язык, обычаи, искусство, знания"]
  ];
  function moduleQA(id) {
    const M = MODULES[id];
    return [
      [`Что входит в ценности этого модуля?`, M.values.join(", ")],
      [`Назови праздники этого модуля.`, M.holidays.join(", ")],
      [`Назови два примера из материала модуля. Как можно объяснить один из них однокласснику?`, M.symbols.join(", ")],
      ["Почему важно уважать людей другой культуры?", "люди разные, уважение помогает жить вместе и избегать конфликтов"]
    ];
  }
  function situations() {
    return [
      ["Одноклассник забыл пенал. Как поступить?", "предложить свою ручку или карандаш, помочь без насмешек"],
      ["Во время рассказа о празднике кто-то засмеялся над незнакомым обычаем. Что можно сказать рассказчику и классу?", "например: «Спасибо за рассказ. Если захочешь, объясни, что означает обычай». Попросить одноклассников выслушать ответ без насмешек"],
      ["Друг совершил ошибку и боится признаться. Как помочь?", "спокойно поговорить, помочь исправить, не осуждать"],
      ["В классе спор о праздниках разных семей. Как решить?", "выслушать всех, найти общее, уважать различия"]
    ];
  }
  function conspect(p) {
    const id = moduleOf(p.topic), M = MODULES[id], g = p.grade;
    const qa = CORE.slice(0, 4).concat(moduleQA(id));
    const situ = situations();
    const previous = typeof previousTopicFor === "function" ? previousTopicFor(p) : "";
    const rows = [
      ["1", "Организационный момент", "1", "Приветствует класс и напоминает правило беседы: выслушивать друг друга.", "Готовятся к работе и называют, как показать, что внимательно слушают."],
      ["2", "Короткое повторение", "3", previous ? `Какой пример из темы «${previous}» вы запомнили?` : "Какой поступок помогает однокласснику почувствовать, что его уважают?", "Один ученик приводит пример. Класс кратко поясняет, почему он подходит."],
      ["3", "Работа с понятием", "9", `Вводит тему «${p.topic}» и предлагает обсудить понятия на примерах: ${qa.slice(0, 3).map(x => x[0]).join(" ")}`, "Объясняют одно понятие своими словами и подбирают пример из школьной жизни."],
      ["4", "Работа с модулем", "8", `${M.name}: ценности — ${M.values.join(", ")}; праздники — ${M.holidays.join(", ")}; примеры для обсуждения — ${M.symbols.join(", ")}.`, "Соотносят пример с изучаемым обычаем или правилом и объясняют свой выбор соседу по парте."],
      ["5", "Физминутка", "2", "Показывает движения короткой разминки.", "Выполняют движения и возвращаются к работе."],
      ["6", "Разбор ситуаций", "10", situ.slice(0, 2).map(([q]) => q).join(" "), "В парах предлагают варианты поступков или реплик и поясняют, как их выбор помогает другому человеку."],
      ["7", "Творческая работа", "8", "Предлагает сделать рисунок, подготовить рассказ о традиции или записать правило уважительной беседы.", "Выбирают формат и добавляют один конкретный пример к своей работе."],
      ["8", "Итог и рефлексия", "3", "Какой пример из урока можно применить в классе?", "Завершают фразу «В следующий раз я могу…» конкретным действием."],
      ["9", "Домашнее задание", "1", "Предлагает рассказать семье о теме или подготовить рисунок.", "Записывают выбранное задание."]
    ];
    const table = "| № | Этап урока | Время | Действия учителя | Действия учеников |\n|---|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const qaT = "| № | Вопрос | Ответ |\n|---|---|---|\n" + qa.map((x, i) => `| ${i + 1} | ${x[0]} | ${x[1]} |`).join("\n");
    const situT = "| № | Ситуация | Как поступить |\n|---|---|---|\n" + situ.map((x, i) => `| ${i + 1} | ${x[0]} | ${x[1]} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** ОРКСЭ · **Модуль:** ${M.name}`,
      "",
      "## Цель урока",
      `Формировать нравственные представления и уважение к культурным традициям на основе темы «${p.topic}».`,
      "",
      "## Планируемые результаты",
      "**Предметные:** понимать понятия темы, объяснять их на примерах.",
      "**Метапредметные:** слушать, сравнивать, аргументировать, работать в паре.",
      "**Личностные:** доброжелательность, уважение к людям и традициям.",
      "",
      "## Опорные знания",
      CORE.slice(0, 4).map(([q, a]) => `- ${q} — ${a}`).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Вопросы и ответы",
      qaT,
      "",
      "## Ситуации для обсуждения",
      situT,
      "",
      "## Творческая работа",
      "Нарисовать семейную традицию или составить правила уважения в классе.",
      "",
      "## Оценивание",
      "Участие в беседе, понимание понятия, умение слушать и аргументировать.",
      "",
      "## Домашнее задание",
      "Рассказать близким о теме урока, подготовить рисунок."
    ].join("\n");
  }
  function worksheet(p) {
    const id = moduleOf(p.topic), M = MODULES[id];
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${p.grade} · **Имя:** ______________________`,
      "",
      "## 1. Понятия",
      CORE.slice(0, 4).map(([q], i) => `${i + 1}) ${q}`).join("\n"),
      "",
      "## 2. Модуль",
      `Ценности: ${M.values.join(", ")}. Праздники: ${M.holidays.join(", ")}.`,
      "",
      "## 3. Ситуация",
      "Опиши добрый поступок, который ты видел или совершил.",
      "",
      "## 4. Творчество",
      "Нарисуй один эпизод традиции из рассказа на уроке или семейной истории по выбору. Подпиши, что делают участники и зачем.",
      "",
      "## 5. Рефлексия",
      "Запиши один уважительный вопрос о незнакомой традиции. Обменяйтесь вопросами и проверьте, даёт ли каждый из них собеседнику возможность объяснить её смысл."
    ].join("\n");
  }
  return { moduleOf, conspect, worksheet, lesson: conspect, MODULES };
})();
