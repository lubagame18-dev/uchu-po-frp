/* «Учу по ФРП» — ОРКСЭ без нейросети.
   Модули: основы православной, исламской, буддийской, иудейской культуры,
   основы мировых религиозных культур, основы светской этики.
   Форма — беседа, работа с понятием, разбор ситуации, творческая работа. */
window.OrksePrimary = (() => {
  "use strict";
  const norm = s => String(s || "").toLowerCase().replace(/ё/g, "е");
  const MODULES = {
    prav: { name: "Основы православной культуры", values: ["вера", "добро", "милосердие", "семья", "забота о ближнем"], holidays: ["Рождество", "Пасха"], symbols: ["храм", "икона", "крест"] },
    islam: { name: "Основы исламской культуры", values: ["вера", "милосердие", "справедливость", "семья", "гостеприимство"], holidays: ["Ураза-байрам", "Курбан-байрам"], symbols: ["мечеть", "полумесяц", "ковёр"] },
    budd: { name: "Основы буддийской культуры", values: ["сострадание", "спокойствие", "уважение к жизни", "мудрость", "доброта"], holidays: ["Новый год", "День рождения Будды"], symbols: ["ступа", "мандала", "статуя Будды"] },
    iuda: { name: "Основы иудейской культуры", values: ["вера", "справедливость", "память", "семья", "ответственность"], holidays: ["Песах", "Ханука"], symbols: ["синагога", "звезда Давида", "Тора"] },
    world: { name: "Основы мировых религиозных культур", values: ["уважение", "понимание", "мир между людьми", "доброта", "честность"], holidays: ["праздники разных религий"], symbols: ["храм", "мечеть", "синагога", "ступа"] },
    ethics: { name: "Основы светской этики", values: ["добро", "справедливость", "совесть", "долг", "уважение"], holidays: ["семейные праздники", "традиции"], symbols: ["правила", "законы", "договор"] }
  };
  function moduleOf(topic) {
    const t = norm(topic);
    if (/православ/.test(t)) return "prav";
    if (/ислам|мусульман/.test(t)) return "islam";
    if (/будд/.test(t)) return "budd";
    if (/иуде|иуда|еврей/.test(t)) return "iuda";
    if (/мир|религи|культур/.test(t)) return "world";
    return "ethics";
  }
  const CORE = [
    ["Что такое добро?", "поступки, которые помогают другим и делают мир лучше"],
    ["Что такое совесть?", "внутреннее чувство, которое подсказывает, что хорошо, а что плохо"],
    ["Что такое долг?", "обязанность, которую человек выполняет по совести"],
    ["Что такое милосердие?", "готовность помочь и проявить сострадание"],
    ["Что такое уважение?", "внимательное и доброе отношение к другому человеку"],
    ["Что такое традиция?", "то, что передаётся из поколения в поколение"],
    ["Что такое семья?", "близкие люди, связанные заботой и поддержкой"],
    ["Что такое культура?", "созданное людьми: язык, обычаи, искусство, знания"]
  ];
  function moduleQA(id) {
    const M = MODULES[id];
    return [
      [`Что входит в ценности этого модуля?`, M.values.join(", ")],
      [`Назови праздники этого модуля.`, M.holidays.join(", ")],
      [`Какие символы связаны с культурой?`, M.symbols.join(", ")],
      ["Почему важно уважать людей другой культуры?", "люди разные, уважение помогает жить вместе и избегать конфликтов"]
    ];
  }
  function situations() {
    return [
      ["Одноклассник забыл пенал. Как поступить?", "предложить свою ручку или карандаш, помочь без насмешек"],
      ["Кто-то смеётся над традициями семьи. Что делать?", "объяснить, что традиции важны, и не поддерживать насмешки"],
      ["Друг совершил ошибку и боится признаться. Как помочь?", "спокойно поговорить, помочь исправить, не осуждать"],
      ["В классе спор о праздниках разных семей. Как решить?", "выслушать всех, найти общее, уважать различия"]
    ];
  }
  function conspect(p) {
    const id = moduleOf(p.topic), M = MODULES[id], g = p.grade;
    const qa = CORE.slice(0, 4).concat(moduleQA(id));
    const situ = situations();
    const rows = [
      ["1", "Организационный момент", "1–2", "Приветствие, настрой на разговор."],
      ["2", "Беседа: что уже знаем", "5–6", `Что вы знаете о теме «${p.topic}»? Какие слова и события вспоминаются?`],
      ["3", "Работа с понятием", "8–9", `Вводим понятие и объясняем: ${qa.slice(0, 3).map(x => x[0]).join("; ")} Обсуждаем, как это проявляется в жизни.`],
      ["4", "Работа с модулем", "6–7", `${M.name}: ценности — ${M.values.join(", ")}; праздники — ${M.holidays.join(", ")}; символы — ${M.symbols.join(", ")}.`],
      ["5", "Физминутка", "2", "Короткая разминка."],
      ["6", "Разбор ситуаций", "8–9", situ.slice(0, 2).map(([q]) => q).join(" ")],
      ["7", "Творческая работа", "5–6", "Рисунок, рассказ о традиции или правила уважения."],
      ["8", "Итог и рефлексия", "2–3", "Что запомнили? Что было важным? Как поступим в жизни?"],
      ["9", "Домашнее задание", "1", "Рассказать семье о теме, подготовить рисунок."]
    ];
    const table = "| № | Этап урока | Время | Что делает учитель и ученики |\n|---|---|---|---|\n" + rows.map(r => "| " + r.join(" | ") + " |").join("\n");
    const qaT = "| № | Вопрос | Ответ |\n|---|---|---|\n" + qa.map((x, i) => `| ${i + 1} | ${x[0]} | ${x[1]} |`).join("\n");
    const situT = "| № | Ситуация | Как поступить |\n|---|---|---|\n" + situ.map((x, i) => `| ${i + 1} | ${x[0]} | ${x[1]} |`).join("\n");
    return [
      `# ${p.topic}`,
      "",
      `**Класс:** ${g} · **Предмет:** ОРКСЭ · **Модуль:** ${M.name}`,
      "",
      "## Цель урока",
      `Формировать нравственные представления и уважение к культурным традициям на основе темы «${p.topic}».`,
      "",
      "## Планируемые результаты",
      "**Предметные:** понимать понятия темы, объяснять их на примерах.",
      "**Метапредметные:** слушать, сравнивать, аргументировать, работать в паре.",
      "**Личностные:** доброжелательность, уважение к людям и традициям.",
      "",
      "## Опорные знания",
      CORE.slice(0, 4).map(([q, a]) => `- ${q} — ${a}`).join("\n"),
      "",
      "## Этапы урока",
      table,
      "",
      "## Вопросы и ответы",
      qaT,
      "",
      "## Ситуации для обсуждения",
      situT,
      "",
      "## Творческая работа",
      "Нарисовать семейную традицию или составить правила уважения в классе.",
      "",
      "## Оценивание",
      "Участие в беседе, понимание понятия, умение слушать и аргументировать.",
      "",
      "## Домашнее задание",
      "Рассказать близким о теме урока, подготовить рисунок."
    ].join("\n");
  }
  function worksheet(p) {
    const id = moduleOf(p.topic), M = MODULES[id];
    return [
      `# Рабочий лист: ${p.topic}`,
      "",
      `**Класс:** ${p.grade} · **Имя:** ______________________`,
      "",
      "## 1. Понятия",
      CORE.slice(0, 4).map(([q], i) => `${i + 1}) ${q}`).join("\n"),
      "",
      "## 2. Модуль",
      `Ценности: ${M.values.join(", ")}. Праздники: ${M.holidays.join(", ")}.`,
      "",
      "## 3. Ситуация",
      "Опиши добрый поступок, который ты видел или совершил.",
      "",
      "## 4. Творчество",
      "Нарисуй традицию своей семьи.",
      "",
      "## 5. Рефлексия",
      "Что было важным на уроке? Что возьмёшь в жизнь?"
    ].join("\n");
  }
  return { moduleOf, conspect, worksheet, lesson: conspect, MODULES };
})();
