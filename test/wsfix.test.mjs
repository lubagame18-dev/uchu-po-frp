/* Проверка починки рабочих листов (js/wsfix.js): псевдокарты/схемы из символов,
   обрывки в обратных кавычках, задачи про несуществующую карту. Запуск: node test/wsfix.test.mjs */
import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert";

const file = new URL("../js/wsfix.js", import.meta.url);
const ctx = { console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(file, "utf8"), ctx, { filename: "wsfix.js" });
const W = ctx.WsFix;

const broken = `# История. Пётр I

### Задание 1. Даты
Соотнесите даты и события.

| Дата | Событие |
|---|---|
| 1703 | Основание Петербурга |

### Задание 2. Текст
Прочитайте текст и ответьте на вопрос.

### Задание 3. Личность
Кто изображён на портрете? \`Пётр I\`

### Задание 4. Карта
Рассмотрите карту на слайде. Найдите и подпишите на схеме ниже: **Санкт-Петербург**, **реку Неву**, **Петропавловскую крепость**. Стрелкой покажите, к какому морю открывает выход Нева.

\`Балтийское море\`
\`↑\`
\`|\`
\`-----------------------------\` \`← устье реки\`
\`|\`
\`река\`
\`|\`
\`город\`

Ответьте: в каком направлении от Москвы находится Петербург? (к северо-западу.)

### Задание 5. Итог
Запишите два события правления Петра I.`;

const cleaned = W.sanitize(broken);
assert.ok(!/карт[аыуе]/i.test(cleaned), "задание с картой удалено");
assert.ok(!/[↑↓←→]/u.test(cleaned), "псевдосхема удалена");
assert.ok(!/`Балтийское море`/.test(cleaned), "подписи не в рамках-коде");
assert.ok(cleaned.includes("### Задание 4. Итог"), "нумерация задач восстановлена");
assert.ok(cleaned.includes("| 1703 | Основание Петербурга |"), "настоящая таблица сохранена");
assert.ok(cleaned.includes("Пётр I") && !cleaned.includes("`Пётр I`"), "имя-подпись распаковано");

const normal = `# Тема

### Задание 1. Схема-опора
Заполните таблицу.

| Шаг | Действие | Пример |
|---|---|---|
| 1 | выдели корень | лесной |

### Задание 2. Формула
Запишите \`H2O\` и \`x = 5\`.`;
assert.equal(W.sanitize(normal).trim(), normal.trim(), "нормальный лист не меняется");

const prose = `### Задание 1. Беседа
Москва — столица России. Санкт-Петербург находится к северо-западу от Москвы.`;
assert.equal(W.sanitize(prose), prose, "проза с тире не ломается");

const r = W.analyze(broken);
assert.equal(r.brokenTasks, 1);
assert.ok(r.diagramLines >= 5);
console.log("WSFIX OK:", JSON.stringify(r));
